import { Check, Copy } from 'lucide-react';
import { useState } from 'react';
import { formatCount, formatScore } from '../lib/format';
import { hookPreview, withoutWords, type LibraryHook } from '../lib/hookLibrary';
import { Card } from './layout/Card';
import { Details } from './layout/Details';
import { QUIET_BUTTON } from './LabStatus';
import { VideoLine } from './VideoChips';

/** How long "Copied" stays on the button. */
const COPIED_MS = 2000;

/** Copies text to the clipboard; false when the browser refuses. */
async function copy(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

function CopyButton({ text }: { readonly text: string }) {
  const [state, setState] = useState<'idle' | 'copied' | 'refused'>('idle');
  const press = (): void => {
    void copy(text).then((done) => {
      setState(done ? 'copied' : 'refused');
      window.setTimeout(() => setState('idle'), COPIED_MS);
    });
  };
  const Icon = state === 'copied' ? Check : Copy;
  return (
    <button
      type="button"
      onClick={press}
      className="flex min-h-9 items-center gap-1.5 rounded px-1 text-body-sm font-semibold text-primary transition-colors hover:text-primary-fixed-dim focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-primary-container"
    >
      <Icon aria-hidden="true" className="h-4 w-4" />
      <span aria-live="polite">
        {state === 'copied' ? 'Copied' : state === 'refused' ? 'Could not copy' : 'Copy hook'}
      </span>
    </button>
  );
}

/** The style the AI named, and the video's score at the right. */
function Top({ hook }: { readonly hook: LibraryHook }) {
  return (
    <div className="flex min-w-0 items-center justify-between gap-2">
      <span
        className={`truncate rounded px-2 py-0.5 text-label ${
          hook.style
            ? 'bg-metric-amber-bg text-metric-amber'
            : 'bg-surface-container-high text-outline'
        }`}
      >
        {hook.style ?? 'style not named yet'}
      </span>
      <span
        title="The video's score: its views against its channel's usual"
        className="flex-none rounded bg-surface-container-high px-2 py-0.5 font-mono text-body-sm font-semibold text-metric-amber"
      >
        {formatScore(hook.score)}
      </span>
    </div>
  );
}

/** The opening in its own words, cut short at first, and what it rests on. */
function Words({ hook, seconds }: { readonly hook: LibraryHook; readonly seconds: number }) {
  const [open, setOpen] = useState(false);
  const preview = hook.text === null ? null : hookPreview(hook.text);
  if (hook.text === null || preview === null) {
    return <p className="text-body-md text-on-surface-variant">{withoutWords(hook)}</p>;
  }
  return (
    <div className="flex flex-col gap-1.5">
      <p className="whitespace-pre-line break-words text-body-md text-on-surface">
        &ldquo;{open ? hook.text : preview.text}&rdquo;
      </p>
      {preview.cut && (
        <button
          type="button"
          aria-expanded={open}
          onClick={() => setOpen((shown) => !shown)}
          className="self-start text-body-sm font-semibold text-primary hover:underline"
        >
          {open ? 'Show less' : 'Show all'}
        </button>
      )}
      <p className="text-body-sm text-outline">
        First {seconds} seconds · {hook.words} words · {formatCount(hook.views)} views
        {hook.autoGenerated ? ' · captions made by listening, which can mishear names' : ''}
      </p>
    </div>
  );
}

interface Props {
  readonly hook: LibraryHook;
  readonly seconds: number;
  /** It is among the idea lab's picks. */
  readonly picked: boolean;
  readonly onUse: () => void;
  /** Takes it as a model for the script that is open; absent when none is. */
  readonly onModel?: (() => void) | undefined;
  /** It is one of the open script's models. */
  readonly modelled?: boolean | undefined;
}

/** One opening of a breakout video: its style and score, its words, and what to do with it. */
export function HookCard({ hook, seconds, picked, onUse, onModel, modelled }: Props) {
  return (
    <Card as="article" id={`hook-${hook.videoId}`} className="h-full">
      <Top hook={hook} />
      <Words hook={hook} seconds={seconds} />
      {hook.how && (
        <Details summary="How it opens">
          <p className="text-body-sm text-on-surface-variant">{hook.how}</p>
        </Details>
      )}
      <div className="mt-auto flex min-w-0 flex-col gap-space-sm border-t border-border-subtle pt-space-sm">
        <VideoLine video={hook} />
        {hook.text !== null && (
          <div className="flex flex-wrap items-center gap-2">
            <button type="button" aria-pressed={picked} onClick={onUse} className={QUIET_BUTTON}>
              {picked ? 'In ideas' : 'Add to ideas'}
            </button>
            {onModel && (
              <button
                type="button"
                aria-pressed={modelled}
                onClick={onModel}
                className={QUIET_BUTTON}
              >
                {modelled ? 'A model for the script' : 'Model this in the script'}
              </button>
            )}
            <span className="ml-auto">
              <CopyButton text={hook.text} />
            </span>
          </div>
        )}
      </div>
    </Card>
  );
}
