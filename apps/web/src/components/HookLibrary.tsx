import { useState } from 'react';
import { formatCount, formatScore, watchUrl } from '../lib/format';
import {
  filterHooks,
  hookPreview,
  hookStyles,
  libraryState,
  withoutWords,
  type LibraryHook,
} from '../lib/hookLibrary';
import { FIELD, LabStatus, NOTE, PILL, PRIMARY_BUTTON, QUIET_BUTTON } from './LabStatus';
import { Outbound } from './NicheCard';
import type { Lab } from './useLab';

/** How long "Copied" stays on the button. */
const COPIED_MS = 2000;

/** Copies text to the clipboard; false when the browser refuses. */
async function copy(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

function CopyButton({ text }: { readonly text: string }) {
  const [state, setState] = useState<'idle' | 'copied' | 'refused'>('idle');
  const press = (): void => {
    void copy(text).then((done) => {
      setState(done ? 'copied' : 'refused');
      window.setTimeout(() => setState('idle'), COPIED_MS);
    });
  };
  const Icon = state === 'copied' ? Check : Copy;
  return (
    <button type="button" onClick={press} className={`flex items-center gap-1.5 ${QUIET_BUTTON}`}>
      <Icon aria-hidden="true" className="h-4 w-4" />
      <span aria-live="polite">
        {state === 'copied' ? 'Copied' : state === 'refused' ? 'Could not copy' : 'Copy hook'}
      </span>
    </button>
  );
}

interface CardProps {
  readonly hook: LibraryHook;
  readonly seconds: number;
  /** It is among the idea lab's picks. */
  readonly picked: boolean;
  readonly onUse: () => void;
  /** Takes it as a model for the script that is open; absent when none is. */
  readonly onModel?: (() => void) | undefined;
  /** It is one of the open script's models. */
  readonly modelled?: boolean | undefined;
}

function HookCard({ hook, seconds, picked, onUse, onModel, modelled }: CardProps) {
  const [open, setOpen] = useState(false);
  const preview = hook.text === null ? null : hookPreview(hook.text);
  return (
    <article
      id={`hook-${hook.videoId}`}
      className="flex min-w-0 scroll-mt-20 flex-col gap-space-sm rounded bg-surface-card p-space-md shadow-md"
    >
      <div className="flex flex-wrap items-center gap-2">
        <span
          className={`${PILL} uppercase ${hook.style ? 'text-primary-fixed-dim' : 'text-outline'}`}
        >
          {hook.style ?? 'style not named yet'}
        </span>
        <span className="rounded-full bg-metric-amber-bg px-2 py-0.5 text-metric-badge text-metric-amber">
          {formatScore(hook.score)}
        </span>
        <span className="text-label-caps text-outline">{formatCount(hook.views)} views</span>
      </div>
      {hook.text === null || preview === null ? (
        <p className="text-body-md text-on-surface-variant">{withoutWords(hook)}</p>
      ) : (
        <>
          <p className="whitespace-pre-line break-words text-body-md text-on-surface">
            {open ? hook.text : preview.text}
          </p>
          {preview.cut && (
            <button
              type="button"
              aria-expanded={open}
              onClick={() => setOpen((shown) => !shown)}
              className="self-start text-body-sm font-semibold text-primary hover:underline"
            >
              {open ? 'Show less' : 'Show all'}
            </button>
          )}
          <p className="text-label-caps text-outline">
            First {seconds} seconds · {hook.words} words
            {hook.autoGenerated ? ' · captions made by listening, which can mishear names' : ''}
          </p>
        </>
      )}
      {hook.how && <p className="text-body-sm text-on-surface-variant">How it works: {hook.how}</p>}
      <p className="truncate text-body-sm text-on-surface">
        <Outbound href={watchUrl(hook.videoId)}>{hook.title}</Outbound>
        <span className="text-outline"> · {hook.channelTitle}</span>
      </p>
      {hook.text !== null && (
        <div className="flex flex-wrap items-center gap-2">
          <CopyButton text={hook.text} />
          <button type="button" aria-pressed={picked} onClick={onUse} className={QUIET_BUTTON}>
            {picked ? 'In the idea lab' : 'Use in idea lab'}
          </button>
          {onModel && (
            <button
              type="button"
              aria-pressed={modelled}
              onClick={onModel}
              className={QUIET_BUTTON}
            >
              {modelled ? 'A model for the script' : 'Model this in the script'}
            </button>
          )}
        </div>
      )}
    </article>
  );
}

interface Props {
  readonly lab: Lab;
  /** An AI run is under way somewhere on the page. */
  readonly busy: boolean;
  readonly centerTitle: string;
  /** The hooks chosen as models for the open script, and the way to choose; absent when none is open. */
  readonly models?: {
    readonly chosen: readonly string[];
    readonly toggle: (videoId: string) => void;
  };
}

/**
 * How the top breakout videos on this map open: the first minute of what
 * each says, in its own words from its captions. The only part an AI adds is
 * a name for the way of opening, and the filters are the names that came back.
 */
export function HookLibrary({ lab, busy, centerTitle, models }: Props) {
  const [query, setQuery] = useState('');
  const [style, setStyle] = useState<string | null>(null);
  const hooks = lab.library?.hooks ?? [];
  const state = libraryState(hooks);
  const styles = hookStyles(hooks);
  const chosenStyle = styles.some((entry) => entry.style === style) ? style : null;
  const shown = filterHooks(hooks, query, chosenStyle);
  const running = lab.jobs.state.status === 'running';
  const seconds = lab.library?.seconds ?? 60;
  return (
    <section
      id="hook-library"
      aria-labelledby="hook-library-title"
      className="w-full scroll-mt-16 bg-space-deep px-gutter-desktop pb-space-xl"
    >
      <div className="mx-auto flex max-w-[1440px] flex-col gap-space-lg">
        <div>
          <div className="flex items-center gap-2">
            <Quote aria-hidden="true" className="h-[22px] w-[22px] flex-none text-metric-amber" />
            <h2
              id="hook-library-title"
              className="text-headline-lg font-bold tracking-tight text-on-surface"
            >
              Hook library
            </h2>
          </div>
          <p className="mt-1 max-w-4xl text-body-md text-on-surface-variant">
            The first {seconds} seconds of what the top breakout videos around {centerTitle} say,
            taken word for word from their captions: no AI writes them. Use a hook as a model for a
            way of opening, never as text to reuse.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-space-sm">
          <button
            type="button"
            disabled={running || state.toRead === 0}
            onClick={lab.buildHooks}
            className={PRIMARY_BUTTON}
          >
            {state.built ? 'Read the missing captions' : 'Build the hook library'}
          </button>
          <button
            type="button"
            disabled={busy || state.withWords === 0}
            onClick={lab.nameHooks}
            className={QUIET_BUTTON}
          >
            {state.unnamed === 0 && state.withWords > 0
              ? 'Name the styles again'
              : 'Name the styles'}
          </button>
          <span className="text-body-sm text-outline">
            {state.toRead > 0
              ? `Building reads the captions of ${state.toRead} videos from YouTube, a request or two each. `
              : ''}
            Naming the styles is an AI run of a minute or two.
          </span>
        </div>

        <LabStatus
          state={lab.jobs.state}
          kinds={['hooks-build', 'hooks-label']}
          working="Working on the hook library"
          takes="Keep this page open."
        />

        {state.built && (
          <div className="flex flex-col gap-space-sm">
            <label className="relative block max-w-md">
              <span className="sr-only">Search the hooks</span>
              <Search
                aria-hidden="true"
                className="pointer-events-none absolute left-3 top-2 h-4 w-4 text-outline"
              />
              <input
                type="search"
                value={query}
                onChange={(event) => setQuery(event.target.value)}
                placeholder="Search the words and the titles"
                className={`${FIELD} pl-9`}
              />
            </label>
            {styles.length > 0 && (
              <div
                role="group"
                aria-label="Filter by style"
                className="flex flex-wrap items-center gap-1.5"
              >
                {[{ style: null, count: hooks.length }, ...styles].map((entry) => (
                  <button
                    key={entry.style ?? 'all'}
                    type="button"
                    aria-pressed={chosenStyle === entry.style}
                    onClick={() => setStyle(entry.style)}
                    className={`whitespace-nowrap rounded-full px-3 py-1.5 text-label-caps uppercase transition-colors ${
                      chosenStyle === entry.style
                        ? 'bg-surface-card font-semibold text-primary shadow-sm'
                        : 'bg-surface-container text-on-surface-variant hover:bg-surface-card hover:text-on-surface'
                    }`}
                  >
                    {entry.style ?? 'All'} · {entry.count}
                  </button>
                ))}
              </div>
            )}
          </div>
        )}

        {lab.library !== null && hooks.length === 0 && (
          <p className={NOTE}>This map has no breakout video to take an opening from yet.</p>
        )}
        {hooks.length > 0 && !state.built && state.toRead > 0 && (
          <p className={NOTE}>
            The library has not been built yet. It will hold the openings of the {hooks.length}{' '}
            strongest breakout videos on this map.
          </p>
        )}
        {state.built && shown.length === 0 && <p className={NOTE}>No hook matches that.</p>}
        {(state.built || state.toRead === 0) && shown.length > 0 && (
          <div className="grid grid-cols-1 gap-space-md xl:grid-cols-2">
            {shown.map((hook) => (
              <HookCard
                key={hook.videoId}
                hook={hook}
                seconds={seconds}
                picked={lab.picks.some((pick) => pick.videoId === hook.videoId)}
                onUse={() =>
                  lab.pick({
                    videoId: hook.videoId,
                    title: hook.title,
                    channelTitle: hook.channelTitle,
                    modelOpening: true,
                  })
                }
                onModel={models ? () => models.toggle(hook.videoId) : undefined}
                modelled={models?.chosen.includes(hook.videoId)}
              />
            ))}
          </div>
        )}
      </div>
    </section>
  );
}
