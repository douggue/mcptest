import { describe, expect, test } from 'vitest';
import {
  MAX_PICKS,
  PHONE_TITLE_CHARS,
  SHORTS_TITLE_CHARS,
  YOUTUBE_TITLE_CHARS,
  batchRequest,
  canGenerate,
  formatChoiceOf,
  formatOptions,
  hookModelOf,
  overlayNote,
  previewNeighbours,
  titleCheck,
  togglePick,
  withKept,
  type ConceptView,
  type Pick,
} from '../src/lib/ideaLab';
import {
  HOOK_PREVIEW_CHARS,
  filterHooks,
  hookPreview,
  hookStyles,
  libraryState,
  type LibraryHook,
} from '../src/lib/hookLibrary';

const pick = (videoId: string, overrides: Partial<Pick> = {}): Pick => ({
  videoId,
  title: `Title of ${videoId}`,
  channelTitle: 'Alpha',
  modelOpening: false,
  ...overrides,
});

const hook = (videoId: string, overrides: Partial<LibraryHook> = {}): LibraryHook => ({
  videoId,
  title: `Title of ${videoId}`,
  channelId: 'UCaaaaaaaaaaaaaaaaaaaaaa',
  channelTitle: 'Alpha',
  views: 9000,
  score: 8,
  captions: 'read',
  autoGenerated: true,
  language: 'en',
  text: 'the river was gone by morning',
  words: 6,
  lastLineAtSeconds: 50,
  style: 'cold open',
  how: 'It starts mid-scene.',
  ...overrides,
});

describe('picking inspiration', () => {
  test('adds a video, and takes it away again on a second press', () => {
    const one = togglePick([], pick('a'));

    expect(one.map((entry) => entry.videoId)).toEqual(['a']);
    expect(togglePick(one, pick('a'))).toEqual([]);
  });

  test('takes at most five, leaving the list as it was past that', () => {
    const five = ['a', 'b', 'c', 'd', 'e'].map((id) => pick(id));

    expect(MAX_PICKS).toBe(5);
    expect(togglePick(five, pick('f'))).toBe(five);
  });

  test('a video picked from the hook library is marked for its opening, even when it was picked before', () => {
    const picked = togglePick([pick('a')], pick('a', { modelOpening: true }));

    expect(picked).toEqual([pick('a', { modelOpening: true })]);
  });

  test('a batch can be asked for once at least one video is picked and nothing is running', () => {
    expect(canGenerate([], false)).toBe(false);
    expect(canGenerate([pick('a')], true)).toBe(false);
    expect(canGenerate([pick('a')], false)).toBe(true);
  });
});

describe('what a batch request carries', () => {
  test('is the picked ids, the openings to model, the length and only what else was chosen', () => {
    const picks = [pick('a'), pick('b', { modelOpening: true })];

    expect(batchRequest('UCx', picks, { format: '', angle: '  ', length: 'long' }, 'auto')).toEqual(
      {
        channel: 'UCx',
        inspiration: ['a', 'b'],
        hookModels: ['b'],
        length: 'long',
      },
    );
    expect(
      batchRequest(
        'UCx',
        picks,
        { format: 'formula:4', angle: ' my angle ', length: 'shorts' },
        'codex',
      ),
    ).toEqual({
      channel: 'UCx',
      inspiration: ['a', 'b'],
      hookModels: ['b'],
      length: 'shorts',
      format: { source: 'formula', id: 4 },
      angle: 'my angle',
      engine: 'codex',
    });
  });
});

describe('the formats the owner can pick from', () => {
  test('are this channel’s stored formulas, then the transfer list’s templates, each under a value that says which', () => {
    const options = formatOptions(
      [{ key: 'why {subject} left', template: 'why {subject} left', subjectCount: 4 }],
      [{ id: 4, formula: 'Why [Thing] Quietly Left', videoCount: 3 }],
    );

    expect(options).toEqual([
      {
        value: 'formula:4',
        label: 'Why [Thing] Quietly Left (3 videos)',
        group: 'Trending formats',
      },
      {
        value: 'transfer:why {subject} left',
        label: 'why {subject} left (4 subjects)',
        group: 'Title formats',
      },
    ]);
  });

  test('turn a chosen value back into what the server takes, and anything else into nothing', () => {
    expect(formatChoiceOf('formula:4')).toEqual({ source: 'formula', id: 4 });
    expect(formatChoiceOf('transfer:why {subject} left: again')).toEqual({
      source: 'transfer',
      key: 'why {subject} left: again',
    });
    expect(formatChoiceOf('')).toBeNull();
    expect(formatChoiceOf('formula:four')).toBeNull();
    expect(formatChoiceOf('elsewhere:1')).toBeNull();
  });
});

describe('a title’s length', () => {
  test('is counted, with the limits named', () => {
    expect(PHONE_TITLE_CHARS).toBe(55);
    expect(SHORTS_TITLE_CHARS).toBe(40);
    expect(YOUTUBE_TITLE_CHARS).toBe(100);
    expect(titleCheck('A short title', 'long')).toEqual({ count: 13, limit: 55, warning: null });
  });

  test('is warned about past the length a phone shows, and again past what YouTube takes', () => {
    const long = 'x'.repeat(56);

    expect(titleCheck(long, 'long').warning).toBe(
      'May be cut off on a phone: 56 characters, and a phone’s feed shows about 55.',
    );
    expect(titleCheck('x'.repeat(41), 'shorts').warning).toMatch(/about 40/);
    expect(titleCheck('x'.repeat(101), 'long').warning).toBe(
      'Too long for YouTube: 101 characters, and a title can be at most 100.',
    );
  });

  test('counts letters as a reader sees them, not as they are stored', () => {
    expect(titleCheck('naïve café 👍🏽', 'long').count).toBe(12);
  });
});

describe('the overlay text', () => {
  test('is fine at four words or fewer and flagged past that', () => {
    expect(overlayNote('STILL RUNNING')).toBeNull();
    expect(overlayNote('one two three four')).toBeNull();
    expect(overlayNote('one two three four five')).toBe('5 words: more than the four asked for.');
  });
});

describe('the two real videos beside a draft', () => {
  const breakout = (videoId: string, score: number) => ({ videoId, score, title: videoId });

  test('are the strongest breakouts on the map, the concept’s own inspiration first', () => {
    const breakouts = [breakout('a', 3), breakout('b', 9), breakout('c', 5), breakout('d', 7)];

    expect(previewNeighbours(breakouts, ['c']).map((one) => one.videoId)).toEqual(['c', 'b']);
    expect(previewNeighbours(breakouts, []).map((one) => one.videoId)).toEqual(['b', 'd']);
    expect(previewNeighbours([breakout('a', 3)], [])).toHaveLength(1);
  });
});

describe('keeping a concept on the page', () => {
  const concept = (id: number, kept: boolean) => ({ id, kept, batchId: 1 }) as ConceptView;

  test('marks it and moves the kept ones to the front, keeping the order otherwise', () => {
    const list = [concept(1, false), concept(2, false), concept(3, true)];

    expect(withKept(list, 2, true).map((one) => [one.id, one.kept])).toEqual([
      [2, true],
      [3, true],
      [1, false],
    ]);
  });
});

describe('the library hook a concept’s opening follows', () => {
  test('is the hook whose video id its hook-style line names', () => {
    const hooks = [hook('aaaaaaaaaa1'), hook('bbbbbbbbbb1', { style: 'number shock' })];

    expect(hookModelOf('bbbbbbbbbb1: number shock', hooks)?.videoId).toBe('bbbbbbbbbb1');
    expect(hookModelOf('zzzzzzzzzz9: made up', hooks)).toBeNull();
    expect(hookModelOf(null, hooks)).toBeNull();
  });
});

describe('the hook library on the page', () => {
  const hooks = [
    hook('aaaaaaaaaa1', { text: 'The river was gone by morning', style: 'cold open' }),
    hook('bbbbbbbbbb1', {
      title: 'Why Rivers Vanish',
      text: 'Nine in ten wells ran dry',
      style: 'number shock',
    }),
    hook('cccccccccc1', { text: 'Picture a bridge', style: 'cold open' }),
    hook('dddddddddd1', { text: 'An unlabelled opening', style: null, how: null }),
    hook('eeeeeeeeee1', { captions: 'none', text: null, style: null, how: null }),
  ];

  test('offers the style names that came back, most used first, and nothing made up', () => {
    expect(hookStyles(hooks)).toEqual([
      { style: 'cold open', count: 2 },
      { style: 'number shock', count: 1 },
    ]);
    expect(hookStyles([hook('a', { style: null })])).toEqual([]);
  });

  test('searches the words and the titles, whatever the capitals', () => {
    expect(filterHooks(hooks, 'RIVER', null).map((one) => one.videoId)).toEqual([
      'aaaaaaaaaa1',
      'bbbbbbbbbb1',
    ]);
    expect(filterHooks(hooks, '  ', null)).toHaveLength(5);
  });

  test('filters by one style, and by both at once', () => {
    expect(filterHooks(hooks, '', 'cold open').map((one) => one.videoId)).toEqual([
      'aaaaaaaaaa1',
      'cccccccccc1',
    ]);
    expect(filterHooks(hooks, 'bridge', 'cold open')).toHaveLength(1);
    expect(filterHooks(hooks, 'bridge', 'number shock')).toEqual([]);
  });

  test('shows the start of a long hook and says there is more', () => {
    const long = 'word '.repeat(200).trim();

    expect(hookPreview('a short hook')).toEqual({ text: 'a short hook', cut: false });
    const preview = hookPreview(long);
    expect(preview.cut).toBe(true);
    expect(preview.text.length).toBeLessThanOrEqual(HOOK_PREVIEW_CHARS + 1);
    expect(preview.text.endsWith('…')).toBe(true);
    expect(preview.text).not.toMatch(/wor…$/);
  });

  test('says where the library stands: not built, built, or built and named', () => {
    const unread = hook('a', { captions: 'not-read', text: null, style: null, how: null });

    expect(libraryState([])).toEqual({ built: false, toRead: 0, withWords: 0, unnamed: 0 });
    expect(libraryState([unread, unread])).toEqual({
      built: false,
      toRead: 2,
      withWords: 0,
      unnamed: 0,
    });
    expect(libraryState(hooks)).toEqual({ built: true, toRead: 0, withWords: 4, unnamed: 1 });
  });
});
