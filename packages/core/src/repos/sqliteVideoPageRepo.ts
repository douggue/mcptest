import { z } from 'zod';
import type { Db } from '../db/sqlite';
import { VIDEO_IMAGE_HOST, isPinnedImageUrl } from '../sources/images';
import type { StoryboardLevel, VideoDetails, VideoTranscript } from '../sources/types';
import type {
  DetailsSource,
  StoredStoryboard,
  StoredTranscript,
  StoredVideoDetails,
  TranscriptRepo,
  VideoDetailsRepo,
} from './types';

/**
 * What was read from videos' own pages: captions, descriptions and tags, and
 * storyboards. Lists are kept as JSON and checked again when read, since a
 * store file is only as trustworthy as whatever last wrote to it.
 */

const segmentsSchema = z.array(
  z.object({ startMs: z.number().int().nonnegative(), text: z.string() }),
);
const tagsSchema = z.array(z.string());
const count = z.number().int().positive();
const levelsSchema = z.array(
  z.object({
    templateUrl: z.string().refine((url) => isPinnedImageUrl(url, { hosts: [VIDEO_IMAGE_HOST] })),
    frameWidth: count,
    frameHeight: count,
    frameCount: count,
    columns: count,
    rows: count,
    intervalMs: z.number().int().nonnegative(),
    sheetCount: count,
  }),
);

interface TranscriptRow {
  video_id: string;
  language: string | null;
  auto_generated: number;
  segments_json: string | null;
  fetched_at: string;
}

interface DetailsRow {
  video_id: string;
  title: string | null;
  description: string;
  tags_json: string;
  duration_s: number | null;
  source: string;
  fetched_at: string;
}

/** Stored JSON read back through a schema; null when it is not what was written. */
function parseStored<T>(schema: z.ZodType<T>, json: string): T | null {
  try {
    const parsed = schema.safeParse(JSON.parse(json));
    return parsed.success ? parsed.data : null;
  } catch {
    return null;
  }
}

export class SqliteVideoPageRepo implements TranscriptRepo, VideoDetailsRepo {
  constructor(private readonly db: Db) {}

  find(videoId: string): StoredTranscript | null {
    const row = this.db
      .prepare<[string], TranscriptRow>(
        `SELECT video_id, language, auto_generated, segments_json, fetched_at
         FROM video_transcripts WHERE video_id = ?`,
      )
      .get(videoId);
    if (!row) return null;
    const fetchedAt = new Date(row.fetched_at);
    if (row.segments_json === null) return { videoId, transcript: null, fetchedAt };
    const segments = parseStored(segmentsSchema, row.segments_json);
    if (segments === null) return null;
    const transcript: VideoTranscript = {
      language: row.language,
      autoGenerated: row.auto_generated === 1,
      segments,
    };
    return { videoId, transcript, fetchedAt };
  }

  save(videoId: string, transcript: VideoTranscript | null, fetchedAt: Date): void {
    this.db
      .prepare(
        `INSERT INTO video_transcripts (video_id, language, auto_generated, segments_json, fetched_at)
         VALUES (@videoId, @language, @autoGenerated, @segments, @fetchedAt)
         ON CONFLICT (video_id) DO UPDATE SET
           language = excluded.language,
           auto_generated = excluded.auto_generated,
           segments_json = excluded.segments_json,
           fetched_at = excluded.fetched_at`,
      )
      .run({
        videoId,
        language: transcript?.language ?? null,
        autoGenerated: transcript?.autoGenerated ? 1 : 0,
        segments: transcript ? JSON.stringify(transcript.segments) : null,
        fetchedAt: fetchedAt.toISOString(),
      });
  }

  findDetails(videoId: string): StoredVideoDetails | null {
    const row = this.db
      .prepare<[string], DetailsRow>(
        `SELECT video_id, title, description, tags_json, duration_s, source, fetched_at
         FROM video_details WHERE video_id = ?`,
      )
      .get(videoId);
    const tags = row ? parseStored(tagsSchema, row.tags_json) : null;
    if (!row || tags === null) return null;
    return {
      videoId,
      title: row.title,
      description: row.description,
      tags,
      durationSeconds: row.duration_s,
      source: row.source === 'api' ? 'api' : 'web',
      fetchedAt: new Date(row.fetched_at),
    };
  }

  saveDetails(
    videoId: string,
    details: VideoDetails,
    source: DetailsSource,
    fetchedAt: Date,
  ): void {
    this.db
      .prepare(
        `INSERT INTO video_details (video_id, title, description, tags_json, duration_s, source, fetched_at)
         VALUES (@videoId, @title, @description, @tags, @durationSeconds, @source, @fetchedAt)
         ON CONFLICT (video_id) DO UPDATE SET
           title = COALESCE(excluded.title, video_details.title),
           description = excluded.description,
           tags_json = excluded.tags_json,
           duration_s = COALESCE(excluded.duration_s, video_details.duration_s),
           source = excluded.source,
           fetched_at = excluded.fetched_at`,
      )
      .run({
        videoId,
        title: details.title,
        description: details.description,
        tags: JSON.stringify(details.tags),
        durationSeconds: details.durationSeconds,
        source,
        fetchedAt: fetchedAt.toISOString(),
      });
  }

  findStoryboard(videoId: string): StoredStoryboard | null {
    const row = this.db
      .prepare<[string], { levels_json: string; fetched_at: string }>(
        'SELECT levels_json, fetched_at FROM video_storyboards WHERE video_id = ?',
      )
      .get(videoId);
    const levels = row ? parseStored(levelsSchema, row.levels_json) : null;
    return row && levels ? { levels, fetchedAt: new Date(row.fetched_at) } : null;
  }

  saveStoryboard(videoId: string, levels: readonly StoryboardLevel[], fetchedAt: Date): void {
    this.db
      .prepare(
        `INSERT INTO video_storyboards (video_id, levels_json, fetched_at)
         VALUES (?, ?, ?)
         ON CONFLICT (video_id) DO UPDATE SET
           levels_json = excluded.levels_json,
           fetched_at = excluded.fetched_at`,
      )
      .run(videoId, JSON.stringify(levels), fetchedAt.toISOString());
  }
}
