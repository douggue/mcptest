import { mkdir, writeFile } from 'node:fs/promises';
import {
  DEFAULT_WINNERS_PER_CHANNEL,
  WINNER_MIN_SCORE,
  boardChannel,
  type ScoredBoardVideo,
} from '../map/thumbnails';
import type { ChannelRepo, VideoRepo } from '../repos/types';
import { CHANNEL_ID_PATTERN, VIDEO_ID_PATTERN } from '../sources/parse';
import type { VideoTranscript } from '../sources/types';
import { readTranscript, type VideoPageDeps } from '../video/pages';
import { clock, formatTranscript, transcriptPace } from '../video/transcriptText';
import { channelFolder, pathInside } from './folder';

/**
 * Saves the transcripts of one channel's videos that took off (the winners
 * the thumbnail download saves pictures of) as text files, with an index
 * saying what each one is. The files are for reading outside the app, or for
 * handing to a tool that reads text from disk.
 */

/** The folder under the downloads folder that holds one folder per channel. */
export const TRANSCRIPTS_FOLDER = 'transcripts';
export const TRANSCRIPT_INDEX_FILE = 'index.json';
/**
 * The most transcripts saved for one channel: as many as the thumbnail
 * download saves winners. A transcript not yet stored costs one request each.
 */
export const TRANSCRIPT_FILES_MAX = DEFAULT_WINNERS_PER_CHANNEL;
const JSON_INDENT = 2;
const MAX_REASON_LENGTH = 200;

export interface TranscriptDownloadDeps extends VideoPageDeps {
  readonly channels: ChannelRepo;
  readonly videos: Pick<VideoRepo, 'listByChannel'>;
}

export interface TranscriptDownloadOptions {
  /** Most transcripts to save. Defaults to `TRANSCRIPT_FILES_MAX`. */
  readonly max?: number;
}

/** One saved transcript, as the index file lists it. */
export interface SavedTranscript {
  readonly videoId: string;
  readonly title: string;
  readonly views: number;
  /** Multiple of the channel's usual views. */
  readonly score: number;
  /** The file's name inside the channel's folder. */
  readonly file: string;
  readonly language: string | null;
  /** Made by YouTube's speech recognition, so names and numbers may be misheard. */
  readonly autoGenerated: boolean;
  readonly words: number;
}

export interface TranscriptDownload {
  readonly channelId: string;
  readonly channelTitle: string;
  /** The channel's folder, as an absolute path. */
  readonly folder: string;
  readonly indexFile: string;
  /** The transcripts now in the folder. */
  readonly saved: readonly SavedTranscript[];
  /** Videos that took off and have no captions on YouTube. */
  readonly noCaptions: readonly { readonly videoId: string; readonly title: string }[];
  readonly failed: readonly { readonly videoId: string; readonly reason: string }[];
}

type Outcome =
  | { readonly kind: 'saved'; readonly entry: SavedTranscript }
  | { readonly kind: 'none'; readonly videoId: string; readonly title: string }
  | { readonly kind: 'failed'; readonly videoId: string; readonly reason: string };

const reasonOf = (error: unknown): string =>
  (error instanceof Error ? error.message : String(error))
    .split(/\r?\n/, 1)[0]
    ?.slice(0, MAX_REASON_LENGTH) ?? '';

/** A transcript as the text of its file: what it is, then the words with their time marks. */
function fileText(video: ScoredBoardVideo, transcript: VideoTranscript, words: number): string {
  const { text, endsAtMs } = formatTranscript(transcript.segments, {
    maxChars: Number.MAX_SAFE_INTEGER,
  });
  const language = `${transcript.language ?? 'language not given'}${transcript.autoGenerated ? ' (auto-generated)' : ''}`;
  return [
    video.title,
    `https://www.youtube.com/watch?v=${video.videoId}`,
    `Captions: ${language} · ${words} words · last line at ${clock(endsAtMs ?? 0)}`,
    '',
    text,
    '',
  ].join('\n');
}

async function saveOne(
  deps: TranscriptDownloadDeps,
  folder: string,
  video: ScoredBoardVideo,
): Promise<Outcome> {
  const { videoId, title } = video;
  try {
    const { transcript } = await readTranscript(deps, videoId);
    if (transcript === null) return { kind: 'none', videoId, title };
    const { words } = transcriptPace(transcript.segments);
    const file = `${videoId}.txt`;
    await writeFile(pathInside(folder, file), fileText(video, transcript, words), 'utf8');
    return {
      kind: 'saved',
      entry: {
        videoId,
        title,
        views: video.views,
        score: video.score,
        file,
        language: transcript.language,
        autoGenerated: transcript.autoGenerated,
        words,
      },
    };
  } catch (error) {
    return { kind: 'failed', videoId, reason: reasonOf(error) };
  }
}

/** One video after another: each transcript not yet stored is a request to YouTube. */
async function saveAll(
  deps: TranscriptDownloadDeps,
  folder: string,
  winners: readonly ScoredBoardVideo[],
): Promise<readonly Outcome[]> {
  let outcomes: readonly Outcome[] = [];
  for (const video of winners) {
    outcomes = [...outcomes, await saveOne(deps, folder, video)];
  }
  return outcomes;
}

/**
 * Saves the transcripts of one stored channel's winning videos under
 * `<root>/transcripts/<channel name>/`, one text file per video named by its
 * id, and writes `index.json` beside them. A stored transcript is used as it
 * is; one not stored is read from YouTube once and kept. A video without
 * captions is named in the answer, not written as an empty file. Returns
 * null when the channel is not in the store.
 */
export async function saveChannelTranscripts(
  deps: TranscriptDownloadDeps,
  channelId: string,
  root: string,
  options: TranscriptDownloadOptions = {},
): Promise<TranscriptDownload | null> {
  if (!CHANNEL_ID_PATTERN.test(channelId)) {
    throw new Error(`Not a valid YouTube channel id: "${channelId.slice(0, 40)}"`);
  }
  const channel = deps.channels.findById(channelId);
  if (!channel) return null;
  const board = boardChannel(
    { ...channel, videos: deps.videos.listByChannel(channelId) },
    deps.now(),
    { winnersPerChannel: options.max ?? TRANSCRIPT_FILES_MAX },
  );
  // A video id becomes a file name, so one that is not an id is never written.
  const winners = board.winners.filter((video) => VIDEO_ID_PATTERN.test(video.videoId));
  const folder = await channelFolder(
    pathInside(root, TRANSCRIPTS_FOLDER),
    channel,
    TRANSCRIPT_INDEX_FILE,
  );
  await mkdir(folder, { recursive: true });
  const outcomes = await saveAll(deps, folder, winners);
  const result = {
    saved: outcomes.flatMap((outcome) => (outcome.kind === 'saved' ? [outcome.entry] : [])),
    noCaptions: outcomes.flatMap((outcome) =>
      outcome.kind === 'none' ? [{ videoId: outcome.videoId, title: outcome.title }] : [],
    ),
    failed: outcomes.flatMap((outcome) =>
      outcome.kind === 'failed' ? [{ videoId: outcome.videoId, reason: outcome.reason }] : [],
    ),
  };
  const indexFile = pathInside(folder, TRANSCRIPT_INDEX_FILE);
  const index = {
    channelId,
    channelTitle: channel.title,
    savedAt: deps.now().toISOString(),
    winnerMinScore: WINNER_MIN_SCORE,
    transcripts: result.saved,
    noCaptions: result.noCaptions,
    failed: result.failed,
  };
  await writeFile(indexFile, `${JSON.stringify(index, null, JSON_INDENT)}\n`, 'utf8');
  return { channelId, channelTitle: channel.title, folder, indexFile, ...result };
}
