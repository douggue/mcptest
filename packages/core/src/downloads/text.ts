import type { BrandResult } from '../channel/brand';
import { formatCount, sanitize } from '../format';
import type { BrandImage } from '../sources/types';
import type { TranscriptResult } from '../video/pages';
import { clock, formatTranscript } from '../video/transcriptText';
import type { ThumbnailDownload } from './thumbnails';
import type { VideoDownload, VideoRoute } from './videoFile';

/**
 * What the command line prints for the downloaders, as lines of plain text.
 * Everything read from YouTube passes through `sanitize`, since a terminal
 * obeys control characters.
 */

const BYTES_PER_MB = 1_000_000;
const ROUTE_NAME: Readonly<Record<VideoRoute, string>> = {
  'yt-dlp': 'yt-dlp',
  'built-in': 'the YouTube library inside Jgtube',
};

/** A video's whole transcript with its time marks, under a line saying what it is. */
export function transcriptLines(result: TranscriptResult): readonly string[] {
  const { transcript } = result;
  if (transcript === null) {
    return [`Video ${result.videoId} has no captions: YouTube lists none for it.`];
  }
  const { text, endsAtMs } = formatTranscript(transcript.segments, {
    maxChars: Number.MAX_SAFE_INTEGER,
  });
  const language = `${transcript.language ?? 'language not given'}${transcript.autoGenerated ? ' (auto-generated)' : ''}`;
  return [
    [
      `Transcript of ${result.videoId}`,
      sanitize(language),
      `${transcript.segments.length} lines`,
      `last line at ${clock(endsAtMs ?? 0)}`,
      result.fromStore ? 'stored copy' : 'read from YouTube and stored',
    ].join(' · '),
    '',
    ...sanitizeLines(text),
  ];
}

/** Text from YouTube as lines safe to print: its own line breaks kept, every other control character gone. */
function sanitizeLines(text: string): readonly string[] {
  return text.split(/\r?\n/).map(sanitize);
}

/** Where a channel's thumbnails were saved, and how it went. */
export function thumbnailLines(result: ThumbnailDownload): readonly string[] {
  const total = result.images.length;
  return [
    `${total} thumbnail${total === 1 ? '' : 's'} of ${sanitize(result.channelTitle)} in ${result.folder}`,
    `${result.saved} saved now, ${result.alreadyThere} already there, ${result.failed.length} could not be fetched.`,
    `What each picture is: ${result.indexFile}`,
    ...result.failed.map((failure) => `  ${failure.videoId}: ${sanitize(failure.reason)}`),
  ];
}

const imageLine = (label: string, images: readonly BrandImage[]): string => {
  const largest = images[0];
  return largest
    ? `${label}: ${largest.url} (${largest.width}×${largest.height})`
    : `${label}: none`;
};

/** How a channel presents itself, a line for each part. */
export function brandLines(result: BrandResult): readonly string[] {
  const { channel, brand } = result;
  const subscribers =
    channel.subscribers === null
      ? 'subscribers hidden'
      : `${formatCount(channel.subscribers)} subscribers`;
  const heading = `${sanitize(channel.title)}${channel.handle ? ` (@${channel.handle})` : ''} · ${subscribers}`;
  if (brand === null) return [heading, 'Its page gave no branding to read.'];
  const bio = (brand.description ?? '').trim();
  return [
    `${heading}${result.fromStore ? ' · stored copy' : ' · read from YouTube and stored'}`,
    ...(bio === '' ? ['Bio: none'] : ['Bio:', ...sanitizeLines(bio).map((line) => `  ${line}`)]),
    `Keywords: ${brand.keywords.length > 0 ? brand.keywords.map(sanitize).join(', ') : 'none'}`,
    `Links: ${brand.links.length > 0 ? brand.links.map(sanitize).join(', ') : 'none'}`,
    imageLine('Logo', brand.avatar),
    imageLine('Cover', brand.banner),
  ];
}

/** Where a video file was saved and what it is, or why there is none. */
export function videoLines(result: VideoDownload): readonly string[] {
  if (!result.ok) {
    const route = result.via === null ? '' : ` (tried with ${ROUTE_NAME[result.via]})`;
    return [`No video file: ${sanitize(result.message)}${route}`];
  }
  const megabytes = (result.bytes / BYTES_PER_MB).toFixed(1);
  const length = result.durationSeconds === null ? [] : [clock(result.durationSeconds * 1000)];
  return [
    `Saved ${result.path}`,
    [
      `${megabytes} MB`,
      ...length,
      sanitize(result.format),
      `fetched with ${ROUTE_NAME[result.via]}`,
    ].join(' · '),
    'This is a temporary copy: delete it when you are done. Copies left behind are removed after a day.',
  ];
}
