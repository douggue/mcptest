import type { StoredTranscript } from '../repos/types';
import { firstMinute, type HookLabel } from './hooks';

/**
 * The hook library as it is read: for each breakout video picked for it, the
 * first minute of what is said, from the stored captions, and the label an
 * engine gave it when one has. A video without captions, or whose captions
 * were never read, is listed as such and never left out silently.
 */

/** A video the library is built from, with its numbers from the store. */
export interface HookSource {
  readonly videoId: string;
  readonly title: string;
  readonly channelId: string;
  readonly channelTitle: string;
  readonly views: number;
  readonly score: number;
}

/** 'none': YouTube lists no captions for it. 'not-read': nobody has asked for them yet. */
export type HookCaptions = 'read' | 'none' | 'not-read';

export interface LibraryHook extends HookSource {
  readonly captions: HookCaptions;
  /** Whether YouTube made the captions by listening, which can mishear names; null without captions. */
  readonly autoGenerated: boolean | null;
  readonly language: string | null;
  /** The first minute of what is said; null without captions, or when nothing is said in it. */
  readonly text: string | null;
  readonly words: number | null;
  /** When the last caption line taken starts, in seconds. */
  readonly lastLineAtSeconds: number | null;
  /** The name an engine gave to the way it opens; null when it has no label yet. */
  readonly style: string | null;
  readonly how: string | null;
}

function hookOf(
  source: HookSource,
  stored: StoredTranscript | null,
  label: HookLabel | undefined,
): LibraryHook {
  const transcript = stored?.transcript ?? null;
  const opening = transcript ? firstMinute(transcript.segments) : null;
  const captions: HookCaptions =
    stored === null ? 'not-read' : transcript === null ? 'none' : 'read';
  return {
    ...source,
    captions,
    autoGenerated: transcript?.autoGenerated ?? null,
    language: transcript?.language ?? null,
    text: opening?.text ?? null,
    words: opening?.words ?? null,
    lastLineAtSeconds: opening?.lastLineAtSeconds ?? null,
    // A label describes the words; without words there is nothing it could be about.
    style: opening ? (label?.style ?? null) : null,
    how: opening ? (label?.how ?? null) : null,
  };
}

/** The library for the given videos, in their order. Reads only what it is handed. */
export function buildHookLibrary(
  sources: readonly HookSource[],
  transcriptOf: (videoId: string) => StoredTranscript | null,
  labels: readonly HookLabel[],
): readonly LibraryHook[] {
  const labelled = new Map(labels.map((label) => [label.videoId, label]));
  return sources.map((source) =>
    hookOf(source, transcriptOf(source.videoId), labelled.get(source.videoId)),
  );
}
