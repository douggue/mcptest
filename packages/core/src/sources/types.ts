export type DatePrecision = 'hour' | 'day' | 'week' | 'month' | 'year';

/** A publish date derived from relative text such as "2w ago". */
export interface ApproxDate {
  readonly date: Date;
  readonly precision: DatePrecision;
  readonly raw: string;
}

export type ChannelRef =
  | { readonly kind: 'id'; readonly id: string }
  | { readonly kind: 'handle'; readonly handle: string };

export interface ChannelInfo {
  readonly id: string;
  readonly title: string;
  readonly handle: string | null;
  readonly subscribers: number | null;
  readonly subscribersHidden: boolean;
  readonly videoCount: number | null;
}

export interface VideoItem {
  readonly id: string;
  readonly channelId: string;
  readonly title: string;
  readonly views: number | null;
  readonly durationSeconds: number | null;
  readonly published: ApproxDate | null;
}

/** A video with the fields needed to store and score it. */
export interface StorableVideo extends VideoItem {
  readonly views: number;
  readonly published: ApproxDate;
}

export interface SidebarItem {
  readonly videoId: string;
  readonly title: string;
  readonly channelId: string | null;
  readonly channelName: string | null;
  readonly channelHandle: string | null;
  readonly views: number | null;
  readonly published: ApproxDate | null;
}

/** One picture a channel page offers, in one of its sizes. */
export interface BrandImage {
  readonly url: string;
  readonly width: number;
  readonly height: number;
}

/** How a channel presents itself, as its own page shows it. */
export interface ChannelBrand {
  /** The channel's description (its bio); empty when it has none, null when the page did not say. */
  readonly description: string | null;
  /** The logo in the sizes offered, largest first; empty when none could be read. */
  readonly avatar: readonly BrandImage[];
  /** The cover across the top of the page, largest first; empty when the channel has none. */
  readonly banner: readonly BrandImage[];
  /** The keywords the channel's owner set. */
  readonly keywords: readonly string[];
  /** The links shown on the channel's header, as text. Never followed. */
  readonly links: readonly string[];
}

export interface ChannelSnapshot {
  readonly channel: ChannelInfo;
  readonly videos: readonly VideoItem[];
  /** Read from the same page as the channel; absent from sources that do not read it. */
  readonly brand?: ChannelBrand;
}

/** One line of a video's captions. */
export interface TranscriptSegment {
  /** Milliseconds from the start of the video. */
  readonly startMs: number;
  readonly text: string;
}

export interface VideoTranscript {
  /** The language code of the captions, such as "en"; null when it is not given. */
  readonly language: string | null;
  /** Made by YouTube's speech recognition, not written by the channel. */
  readonly autoGenerated: boolean;
  readonly segments: readonly TranscriptSegment[];
}

/**
 * One size of a video's storyboard: sprite sheets of small frames taken at a
 * regular interval through the video, which YouTube publishes for the preview
 * shown when a viewer drags along the timeline.
 */
export interface StoryboardLevel {
  /** The address of a sheet, with `$M` where the sheet's number goes. */
  readonly templateUrl: string;
  readonly frameWidth: number;
  readonly frameHeight: number;
  /** Frames in the whole video at this size. */
  readonly frameCount: number;
  /** Frames across and down one sheet. */
  readonly columns: number;
  readonly rows: number;
  /** Milliseconds between frames; 0 when the frames are spread evenly over the video. */
  readonly intervalMs: number;
  readonly sheetCount: number;
}

/** What a watch page says about a video beyond the channel listing. */
export interface VideoDetails {
  readonly title: string | null;
  readonly description: string;
  readonly tags: readonly string[];
  readonly durationSeconds: number | null;
}

export interface VideoPage {
  readonly videoId: string;
  /** Null when the page could not be read for them. */
  readonly details: VideoDetails | null;
  /** Empty when the video has no storyboard. */
  readonly storyboard: readonly StoryboardLevel[];
  /** Present only when asked for; null when the video has no captions. */
  readonly transcript?: VideoTranscript | null;
}

export interface VideoPageOptions {
  /** Also read the captions, which costs one more request. */
  readonly transcript?: boolean;
}

/** Everything the engine needs from YouTube, so the access method can be swapped. */
export interface YouTubeSource {
  resolveChannelId(handle: string): Promise<string>;
  fetchChannel(channelId: string, maxVideos: number): Promise<ChannelSnapshot>;
  getSidebar(videoId: string): Promise<readonly SidebarItem[]>;
  /**
   * One video's own page: its description and tags, its storyboard and, when
   * asked, its captions. A video without captions is a normal answer
   * (`transcript: null`), not a failure.
   */
  fetchVideoPage(videoId: string, options?: VideoPageOptions): Promise<VideoPage>;
}
