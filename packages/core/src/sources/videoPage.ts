import { VIDEO_IMAGE_HOST, isPinnedImageUrl } from './images';
import { asArray, at, isRecord, textOf } from './mappers';
import type { StoryboardLevel, TranscriptSegment, VideoDetails, VideoTranscript } from './types';

/**
 * Maps what the YouTube client returns for one video's own page into domain
 * objects: its description and tags, its storyboard, and its captions.
 *
 * As in `mappers.ts`, the inputs are untrusted and change shape without
 * notice: every access is guarded, every text is cut to a bound, every
 * address is checked against the one host it may be on, and what cannot be
 * read maps to null or an empty list rather than throwing.
 */

/** YouTube's own limit on a description; anything longer is not one. */
const MAX_DESCRIPTION_LENGTH = 5000;
const MAX_TITLE_LENGTH = 300;
/** YouTube allows 500 characters of tags in all, so these bounds are generous. */
const MAX_TAGS = 60;
const MAX_TAG_LENGTH = 100;
/** A day of video: far past any real length, and a bound on what is stored. */
const MAX_DURATION_SECONDS = 24 * 60 * 60;
/** A caption line is a few words; a transcript of a long video is a few thousand lines. */
const MAX_SEGMENT_LENGTH = 500;
const MAX_SEGMENTS = 20_000;
/** Bounds on a storyboard's numbers: past these it is not a storyboard. */
const MAX_FRAME_SIDE = 2000;
const MAX_GRID_SIDE = 20;
const MAX_FRAMES = 100_000;
const MAX_SHEETS = 5000;
const STORYBOARD_PATH = '/sb/';
/** The sheet's number goes where the address has this. */
export const SHEET_SLOT = '$M';

const CAPTION_HOST = 'www.youtube.com';
const CAPTION_PATH = '/api/timedtext';
/** The caption format with a start time for each line, as JSON. */
const CAPTION_FORMAT = 'json3';
const AUTO_GENERATED_KIND = 'asr';
const AUTO_GENERATED_NAME = /auto-generated/i;

function longText(value: unknown, maxLength: number): string | null {
  const text = typeof value === 'string' ? value : textOf(value);
  return text === null ? null : text.slice(0, maxLength);
}

function wholeNumber(value: unknown, min: number, max: number): number | null {
  const number = typeof value === 'string' && /^\d{1,9}$/.test(value) ? Number(value) : value;
  return typeof number === 'number' && Number.isInteger(number) && number >= min && number <= max
    ? number
    : null;
}

function tagsOf(info: unknown): readonly string[] {
  const listed = [at(info, 'keywords'), at(info, 'tags')].find((list) => Array.isArray(list));
  return asArray(listed)
    .filter((tag): tag is string => typeof tag === 'string' && tag.trim() !== '')
    .slice(0, MAX_TAGS)
    .map((tag) => tag.trim().slice(0, MAX_TAG_LENGTH));
}

/** A video's title, description, tags and length; null when the page gave neither of the first two. */
export function mapVideoDetails(info: unknown): VideoDetails | null {
  const title = longText(at(info, 'title'), MAX_TITLE_LENGTH);
  const description = longText(at(info, 'short_description'), MAX_DESCRIPTION_LENGTH);
  if (title === null && description === null) return null;
  return {
    title,
    description: description ?? '',
    tags: tagsOf(info),
    durationSeconds: wholeNumber(at(info, 'duration'), 0, MAX_DURATION_SECONDS),
  };
}

/** Whether a sheet address is on the video image host, in the storyboard folder. */
function isSheetAddress(url: string): boolean {
  if (!isPinnedImageUrl(url, { hosts: [VIDEO_IMAGE_HOST] })) return false;
  return new URL(url).pathname.startsWith(STORYBOARD_PATH);
}

function mapLevel(board: unknown): StoryboardLevel | null {
  if (!isRecord(board) || board['type'] !== 'vod') return null;
  const templateUrl = typeof board['template_url'] === 'string' ? board['template_url'] : '';
  const level = {
    frameWidth: wholeNumber(board['thumbnail_width'], 1, MAX_FRAME_SIDE),
    frameHeight: wholeNumber(board['thumbnail_height'], 1, MAX_FRAME_SIDE),
    frameCount: wholeNumber(board['thumbnail_count'], 1, MAX_FRAMES),
    columns: wholeNumber(board['columns'], 1, MAX_GRID_SIDE),
    rows: wholeNumber(board['rows'], 1, MAX_GRID_SIDE),
    intervalMs: wholeNumber(board['interval'], 0, MAX_DURATION_SECONDS * 1000),
    sheetCount: wholeNumber(board['storyboard_count'], 1, MAX_SHEETS),
  };
  if (!isSheetAddress(templateUrl) || Object.values(level).includes(null)) return null;
  return { templateUrl, ...(level as Record<keyof typeof level, number>) };
}

/** The sizes of a video's storyboard, as the page lists them; empty when it has none. */
export function mapStoryboard(storyboards: unknown): readonly StoryboardLevel[] {
  return asArray(at(storyboards, 'boards')).flatMap((board) => {
    const level = mapLevel(board);
    return level ? [level] : [];
  });
}

/** One caption track: where to read it, its language, and who wrote it. */
export interface CaptionTrack {
  readonly url: string;
  readonly language: string | null;
  readonly autoGenerated: boolean;
}

function mapTrack(track: unknown): CaptionTrack | null {
  const baseUrl = at(track, 'base_url');
  if (typeof baseUrl !== 'string') return null;
  let url: URL;
  try {
    url = new URL(baseUrl);
  } catch {
    return null;
  }
  const isCaptionAddress =
    url.protocol === 'https:' &&
    url.hostname === CAPTION_HOST &&
    url.port === '' &&
    url.username === '' &&
    url.pathname === CAPTION_PATH;
  if (!isCaptionAddress) return null;
  url.searchParams.set('fmt', CAPTION_FORMAT);
  const language = at(track, 'language_code');
  return {
    url: url.toString(),
    language: typeof language === 'string' ? language.slice(0, 20) : null,
    autoGenerated: at(track, 'kind') === AUTO_GENERATED_KIND,
  };
}

/**
 * The caption track to read: the one for the video's original audio when the
 * page says which that is, otherwise the first. A track whose address is not
 * YouTube's own caption address is never taken. Null when there is none.
 */
export function pickCaptionTrack(captions: unknown): CaptionTrack | null {
  const tracks = asArray(at(captions, 'caption_tracks')).map(mapTrack);
  const audio = asArray(at(captions, 'audio_tracks'));
  const chosenAudio = audio[wholeNumber(at(captions, 'default_audio_track_index'), 0, 1000) ?? 0];
  const original = asArray(at(chosenAudio, 'caption_track_indices'))
    .map((index) => tracks[wholeNumber(index, 0, tracks.length) ?? -1] ?? null)
    .find((track) => track !== null);
  return original ?? tracks.find((track) => track !== null) ?? null;
}

function segmentOf(startMs: unknown, text: string): TranscriptSegment | null {
  const start = wholeNumber(startMs, 0, MAX_DURATION_SECONDS * 1000);
  const clean = text.replace(/\s+/g, ' ').trim().slice(0, MAX_SEGMENT_LENGTH);
  return start === null || clean === '' ? null : { startMs: start, text: clean };
}

/** The caption lines in a timed-text answer (the "json3" format); empty when it is not one. */
export function parseTimedText(body: unknown): readonly TranscriptSegment[] {
  return asArray(at(body, 'events'))
    .flatMap((event) => {
      const words = asArray(at(event, 'segs'))
        .map((piece) => at(piece, 'utf8'))
        .filter((piece): piece is string => typeof piece === 'string');
      const segment = segmentOf(at(event, 'tStartMs'), words.join(''));
      return segment ? [segment] : [];
    })
    .slice(0, MAX_SEGMENTS);
}

/**
 * The transcript the library's own transcript call returns (the panel a
 * viewer opens under a video); null when it holds no line.
 */
export function mapTranscriptPanel(panel: unknown): VideoTranscript | null {
  const lines = asArray(at(panel, 'transcript', 'content', 'body', 'initial_segments'));
  const segments = lines
    .flatMap((line) => {
      const segment = segmentOf(at(line, 'start_ms'), textOf(at(line, 'snippet')) ?? '');
      return segment ? [segment] : [];
    })
    .slice(0, MAX_SEGMENTS);
  if (segments.length === 0) return null;
  const selected = at(panel, 'selectedLanguage');
  const language = typeof selected === 'string' ? selected.slice(0, 60) : null;
  return { language, autoGenerated: AUTO_GENERATED_NAME.test(language ?? ''), segments };
}
