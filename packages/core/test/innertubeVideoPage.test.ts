import { describe, expect, test } from 'vitest';
import { InnertubeSource, type FetchText, type InnertubeClient } from '../src/sources/innertube';
import { RateLimiter } from '../src/sources/limiter';
import channelFixture from './fixtures/channel.json';
import timedText from './fixtures/timedtext.json';
import unplayable from './fixtures/video-page-unplayable.json';
import playable from './fixtures/video-page.json';

const NOW = new Date('2026-11-20T12:00:00Z');
const VIDEO_ID = 'bArCA8xnLqU';
const CHANNEL_ID = 'UCHnyfMqiRRG1u-2MsSQLbXA';

const limiter = new RateLimiter({
  concurrency: 2,
  minDelayMs: 0,
  maxDelayMs: 0,
  maxRetries: 0,
  baseBackoffMs: 0,
  sleep: async () => {},
});

interface Calls {
  readonly player: Array<[string, string]>;
  readonly watch: string[];
  readonly captions: string[];
}

function setUp(
  overrides: Partial<InnertubeClient> = {},
  captionAnswer: () => Response = () => Response.json(timedText),
) {
  const calls: Calls = { player: [], watch: [], captions: [] };
  const client: InnertubeClient = {
    resolveURL: async () => ({}),
    getChannel: async () => ({
      header: channelFixture.header,
      metadata: channelFixture.metadata,
      getVideos: async () => ({
        videos: [],
        has_continuation: false,
        getContinuation: async () => {
          throw new Error('no more pages');
        },
      }),
    }),
    getBasicInfo: async (videoId, options) => {
      calls.player.push([videoId, options.client]);
      return playable;
    },
    getInfo: async (videoId) => {
      calls.watch.push(videoId);
      return { watch_next_feed: [] };
    },
    ...overrides,
  };
  const fetchText: FetchText = async (url, init) => {
    calls.captions.push(url);
    expect(init.redirect).toBe('error');
    expect(init.signal).toBeInstanceOf(AbortSignal);
    return captionAnswer();
  };
  return { calls, source: new InnertubeSource(client, limiter, () => NOW, fetchText) };
}

describe('InnertubeSource.fetchChannel', () => {
  test('reads how the channel presents itself from the same page, with no further request', async () => {
    const { source } = setUp();

    const snapshot = await source.fetchChannel(CHANNEL_ID, 10);

    expect(snapshot.brand?.banner[0]).toMatchObject({ width: 2560 });
    expect(snapshot.brand?.description).toMatch(/^An element of truth/);
  });
});

describe('InnertubeSource.fetchVideoPage', () => {
  test('reads the description, length and storyboard with one request', async () => {
    const { source, calls } = setUp();

    const page = await source.fetchVideoPage(VIDEO_ID);

    expect(page.videoId).toBe(VIDEO_ID);
    expect(page.details).toMatchObject({ durationSeconds: 1554, tags: [] });
    expect(page.storyboard).toHaveLength(3);
    expect(page).not.toHaveProperty('transcript');
    expect(calls).toEqual({ player: [[VIDEO_ID, 'ANDROID_VR']], watch: [], captions: [] });
  });

  test('reads the captions of the original audio when asked, with one more request', async () => {
    const { source, calls } = setUp();

    const page = await source.fetchVideoPage(VIDEO_ID, { transcript: true });

    expect(page.transcript).toMatchObject({ language: 'en', autoGenerated: true });
    expect(page.transcript?.segments[0]).toEqual({
      startMs: 600,
      text: 'Right now, under millions of American',
    });
    expect(calls.captions).toHaveLength(1);
    expect(new URL(calls.captions[0] ?? '').searchParams.get('lang')).toBe('en');
    expect(calls.watch).toEqual([]);
  });

  test('answers "none" for a video without captions, and asks for nothing more', async () => {
    const { source, calls } = setUp({
      getBasicInfo: async () => ({ ...playable, captions: undefined }),
    });

    const page = await source.fetchVideoPage(VIDEO_ID, { transcript: true });

    expect(page.transcript).toBeNull();
    expect(calls.captions).toEqual([]);
    expect(calls.watch).toEqual([]);
  });

  test('answers "none" when the caption track holds no line', async () => {
    const { source } = setUp({}, () => Response.json({ events: [] }));

    expect((await source.fetchVideoPage(VIDEO_ID, { transcript: true })).transcript).toBeNull();
  });

  test('refuses anything that is not a video id before asking YouTube', async () => {
    const { source, calls } = setUp();

    await expect(source.fetchVideoPage('../../etc/passwd')).rejects.toThrow(/video id/);
    expect(calls.player).toEqual([]);
  });

  test.each([
    ['refuses the captions', () => new Response('no', { status: 403 }), /status 403/],
    ['sends something that is not JSON', () => new Response('<html>'), /could not be read/],
    [
      'sends far more than captions ever are',
      () => new Response(new Uint8Array(5_000_001)),
      /too large/,
    ],
  ])('fails in plain words when YouTube %s', async (_what, answer, message) => {
    const { source } = setUp({}, answer);

    await expect(source.fetchVideoPage(VIDEO_ID, { transcript: true })).rejects.toThrow(message);
  });
});

describe('InnertubeSource.fetchVideoPage, when the player will not answer', () => {
  const panel = {
    selectedLanguage: 'English',
    transcript: {
      content: { body: { initial_segments: [{ start_ms: '1200', snippet: { text: 'Hello' } }] } },
    },
  };
  const watchPage = (getTranscript: () => Promise<unknown>) => ({
    watch_next_feed: [],
    basic_info: { title: 'From the watch page', short_description: 'Its description' },
    getTranscript,
  });

  test('takes the details the player still gave and reads the transcript the documented way', async () => {
    const { source, calls } = setUp({
      getBasicInfo: async () => unplayable,
      getInfo: async () => watchPage(async () => panel),
    });

    const page = await source.fetchVideoPage(VIDEO_ID, { transcript: true });

    expect(page.details?.title).toBe("America's New Material Could END POTHOLES Forever!");
    expect(page.storyboard).toEqual([]);
    expect(page.transcript).toEqual({
      language: 'English',
      autoGenerated: false,
      segments: [{ startMs: 1200, text: 'Hello' }],
    });
    expect(calls.captions).toEqual([]);
  });

  test('reads the details from the watch page when the player gave none', async () => {
    const { source } = setUp({
      getBasicInfo: async () => ({ playability_status: { status: 'LOGIN_REQUIRED' } }),
      getInfo: async () => watchPage(async () => panel),
    });

    const page = await source.fetchVideoPage(VIDEO_ID);

    expect(page.details).toMatchObject({ title: 'From the watch page' });
    expect(page).not.toHaveProperty('transcript');
  });

  test('answers "none" when the watch page has no transcript panel', async () => {
    const { source } = setUp({
      getBasicInfo: async () => unplayable,
      getInfo: async () =>
        watchPage(async () => {
          throw new Error('Transcript panel not found. Video likely has no transcript.');
        }),
    });

    expect((await source.fetchVideoPage(VIDEO_ID, { transcript: true })).transcript).toBeNull();
  });

  test('fails, without calling it "none", when YouTube refuses the transcript', async () => {
    const { source } = setUp({
      getBasicInfo: async () => unplayable,
      getInfo: async () =>
        watchPage(async () => {
          throw new Error(
            'Request to https://www.youtube.com/youtubei/v1/get_transcript?prettyPrint=false failed with status code 400',
          );
        }),
    });

    await expect(source.fetchVideoPage(VIDEO_ID, { transcript: true })).rejects.toThrow(
      /captions of video bArCA8xnLqU could not be read/,
    );
  });
});
