import { describe, expect, test } from 'vitest';
import type { BrandResult } from '../src/channel/brand';
import {
  brandLines,
  thumbnailLines,
  transcriptFileLines,
  transcriptLines,
  videoLines,
} from '../src/downloads/text';

const NOW = new Date('2026-11-20T12:00:00Z');
const VIDEO = 'bArCA8xnLqU';
const CHANNEL = `UC${'a'.repeat(22)}`;

describe('transcriptLines', () => {
  const segments = [
    { startMs: 600, text: 'Right now' },
    { startMs: 31_000, text: 'a crack\u001b[31m is spreading' },
  ];

  test('heads the transcript with what it is, then prints it with its time marks', () => {
    const lines = transcriptLines({
      videoId: VIDEO,
      transcript: { language: 'en', autoGenerated: true, segments },
      fetchedAt: NOW,
      fromStore: false,
    });

    expect(lines).toEqual([
      `Transcript of ${VIDEO} · en (auto-generated) · 2 lines · last line at 0:31 · read from YouTube and stored`,
      '',
      '[0:00] Right now',
      // The escape character a caption carried is not passed on to the terminal.
      '[0:31] a crack [31m is spreading',
    ]);
  });

  test('says when the copy came from the store, and when the language is not given', () => {
    const [heading] = transcriptLines({
      videoId: VIDEO,
      transcript: { language: null, autoGenerated: false, segments },
      fetchedAt: NOW,
      fromStore: true,
    });

    expect(heading).toContain('language not given · 2 lines');
    expect(heading).toMatch(/stored copy$/);
  });

  test('says plainly that a video has no captions', () => {
    expect(
      transcriptLines({ videoId: VIDEO, transcript: null, fetchedAt: NOW, fromStore: false }),
    ).toEqual([`Video ${VIDEO} has no captions: YouTube lists none for it.`]);
  });
});

describe('transcriptFileLines', () => {
  test('says where the files are, and names the videos with no captions or that failed', () => {
    const lines = transcriptFileLines({
      channelId: CHANNEL,
      channelTitle: 'Some Bakery',
      folder: '/data/downloads/transcripts/UCa',
      indexFile: '/data/downloads/transcripts/UCa/index.json',
      saved: [
        {
          videoId: VIDEO,
          title: 'A video',
          views: 1,
          score: 3,
          file: `${VIDEO}.txt`,
          language: 'en',
          autoGenerated: true,
          words: 900,
        },
      ],
      noCaptions: [{ videoId: 'aaaaaaaaaaa', title: 'Silent' }],
      failed: [{ videoId: 'bbbbbbbbbbb', reason: 'YouTube did not answer' }],
    });

    expect(lines).toEqual([
      '1 transcript of Some Bakery in /data/downloads/transcripts/UCa',
      '1 of its videos that took off have no captions, 1 could not be read.',
      'What each file is: /data/downloads/transcripts/UCa/index.json',
      '  aaaaaaaaaaa: no captions',
      '  bbbbbbbbbbb: YouTube did not answer',
    ]);
  });
});

describe('thumbnailLines', () => {
  test('says where the pictures are and how it went', () => {
    const image = {
      videoId: VIDEO,
      title: 'A video',
      views: 1,
      score: 3,
      group: 'winner' as const,
      file: `${VIDEO}.jpg`,
    };

    expect(
      thumbnailLines({
        channelId: CHANNEL,
        channelTitle: 'Some Bakery',
        folder: '/data/downloads/thumbnails/UCa',
        indexFile: '/data/downloads/thumbnails/UCa/index.json',
        saved: 1,
        alreadyThere: 0,
        failed: [{ videoId: 'aaaaaaaaaaa', reason: 'it took too long to load' }],
        images: [image],
      }),
    ).toEqual([
      '1 thumbnail of Some Bakery in /data/downloads/thumbnails/UCa',
      '1 saved now, 0 already there, 1 could not be fetched.',
      'What each picture is: /data/downloads/thumbnails/UCa/index.json',
      '  aaaaaaaaaaa: it took too long to load',
    ]);
  });
});

describe('brandLines', () => {
  const channel = {
    id: CHANNEL,
    title: 'Some Bakery',
    handle: 'somebakery',
    subscribers: 8310,
    subscribersHidden: false,
    videoCount: 23,
    fetchedAt: NOW,
  };
  const result = (overrides: Partial<NonNullable<BrandResult['brand']>> = {}): BrandResult => ({
    channel,
    fromStore: false,
    brand: {
      channelId: CHANNEL,
      description: 'We bake bread.\nEvery week.',
      avatar: [{ url: 'https://yt3.googleusercontent.com/logo=s900', width: 900, height: 900 }],
      banner: [],
      keywords: ['bread', 'sourdough starter'],
      links: ['somebakery.example'],
      fetchedAt: NOW,
      ...overrides,
    },
  });

  test('prints each part of how the channel presents itself', () => {
    expect(brandLines(result())).toEqual([
      'Some Bakery (@somebakery) · 8.3K subscribers · read from YouTube and stored',
      'Bio:',
      '  We bake bread.',
      '  Every week.',
      'Keywords: bread, sourdough starter',
      'Links: somebakery.example',
      'Logo: https://yt3.googleusercontent.com/logo=s900 (900×900)',
      'Cover: none',
    ]);
  });

  test('says "none" for each part a channel has not set', () => {
    const lines = brandLines({
      ...result({ description: '', keywords: [], links: [], avatar: [] }),
      fromStore: true,
    });

    expect(lines).toEqual([
      'Some Bakery (@somebakery) · 8.3K subscribers · stored copy',
      'Bio: none',
      'Keywords: none',
      'Links: none',
      'Logo: none',
      'Cover: none',
    ]);
  });

  test('says so when the page gave nothing, and when the subscriber count is hidden', () => {
    expect(
      brandLines({
        channel: { ...channel, handle: null, subscribers: null, subscribersHidden: true },
        brand: null,
        fromStore: false,
      }),
    ).toEqual(['Some Bakery · subscribers hidden', 'Its page gave no branding to read.']);
  });
});

describe('videoLines', () => {
  test('says where the file is, how big, how long, in what format and how it was fetched', () => {
    expect(
      videoLines({
        ok: true,
        path: '/data/downloads/video-temp/wE5ETbiq1qQ.mp4',
        bytes: 41_734_000,
        durationSeconds: 948,
        format: '360p mp4',
        via: 'built-in',
      }),
    ).toEqual([
      'Saved /data/downloads/video-temp/wE5ETbiq1qQ.mp4',
      '41.7 MB · 15:48 · 360p mp4 · fetched with the YouTube library inside Jgtube',
      'This is a temporary copy: delete it when you are done. Copies left behind are removed after a day.',
    ]);
  });

  test('gives the reason when there is no file', () => {
    expect(
      videoLines({ ok: false, kind: 'too-large', message: 'It is over 95 MB.', via: 'yt-dlp' }),
    ).toEqual(['No video file: It is over 95 MB. (tried with yt-dlp)']);
    expect(
      videoLines({ ok: false, kind: 'unreadable', message: 'No way to fetch.', via: null }),
    ).toEqual(['No video file: No way to fetch.']);
  });
});
