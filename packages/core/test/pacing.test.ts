import { describe, expect, test } from 'vitest';
import type { ChannelHistory } from '../src/changes/changes';
import { comparePacing, winnerVideos } from '../src/pacing/compare';
import { spreadOf } from '../src/pacing/spread';
import type { StoredVideo } from '../src/repos/types';
import type { VideoTranscript } from '../src/sources/types';

const NOW = new Date('2026-11-21T12:00:00Z');
const DAY_MS = 86_400_000;
const daysAgo = (days: number) => new Date(NOW.getTime() - days * DAY_MS);

const video = (id: string, seconds: number | null, views = 1000, days = 40): StoredVideo => ({
  id: id.padEnd(11, '_'),
  channelId: `UC${'a'.repeat(22)}`,
  title: 'T',
  views,
  durationSeconds: seconds,
  published: { date: daysAgo(days), precision: 'day', raw: `${days}d ago` },
  fetchedAt: NOW,
});

/** Captions of `words` words whose lines run from 0 to `seconds`. */
const captions = (words: number, seconds: number): VideoTranscript => ({
  language: 'en',
  autoGenerated: false,
  segments: Array.from({ length: 10 }, (_, index) => ({
    startMs: (index * seconds * 1000) / 9,
    text: Array.from({ length: words / 10 }, () => 'word').join(' '),
  })),
});

describe('spreadOf', () => {
  test('gives the median and the middle half, with how many values it rests on', () => {
    expect(spreadOf([1, 2, 3, 4, 5])).toEqual({ count: 5, median: 3, lower: 2, upper: 4 });
    expect(spreadOf([10, 20])).toEqual({ count: 2, median: 15, lower: 12.5, upper: 17.5 });
    expect(spreadOf([])).toEqual({ count: 0, median: null, lower: null, upper: null });
  });
});

describe('winnerVideos', () => {
  test("takes each look-alike's breakouts of the last 30 days, at most 4 a channel", () => {
    const history: ChannelHistory = {
      channel: {
        id: `UC${'a'.repeat(22)}`,
        title: 'A',
        handle: null,
        subscribers: 1000,
        subscribersHidden: false,
        videoCount: null,
        fetchedAt: NOW,
      },
      videos: [
        ...[1, 2, 3, 4, 5, 6].map((n) => video(`old${n}`, 600, 1000, 40 + n)),
        ...[1, 2, 3, 4, 5].map((n) => video(`hit${n}`, 900, 20_000 + n, 5 + n)),
        video('agedhit', 900, 90_000, 60),
      ],
      readings: [],
    };

    const winners = winnerVideos([history], NOW);

    expect(winners).toHaveLength(4);
    expect(winners.every((entry) => entry.id.startsWith('hit'))).toBe(true);
  });
});

describe('comparePacing', () => {
  test('compares lengths, leaving Shorts out of both and counting them', () => {
    const own = [video('o1', 600), video('o2', 720), video('o3', 30), video('o4', null)];
    const winners = [video('w1', 900), video('w2', 1200), video('w3', 45)];

    const pacing = comparePacing({ own, winners, transcriptOf: () => null });

    expect(pacing.lengths.own).toEqual({ count: 2, median: 660, lower: 630, upper: 690 });
    expect(pacing.lengths.winners).toEqual({ count: 2, median: 1050, lower: 975, upper: 1125 });
    expect(pacing.shortsLeftOut).toEqual({ own: 1, winners: 1 });
    expect(pacing.wordsPerMinute.own.count).toBe(0);
  });

  test('compares words a minute where captions are stored', () => {
    const own = [video('o1', 600), video('o2', 600)];
    const winners = [video('w1', 600)];
    const stored: Record<string, VideoTranscript> = {
      [own[0]?.id ?? '']: captions(1500, 600),
      [winners[0]?.id ?? '']: captions(1800, 600),
    };

    const pacing = comparePacing({ own, winners, transcriptOf: (id) => stored[id] ?? null });

    expect(pacing.wordsPerMinute.own).toMatchObject({ count: 1, median: 150 });
    expect(pacing.wordsPerMinute.winners).toMatchObject({ count: 1, median: 180 });
  });
});
