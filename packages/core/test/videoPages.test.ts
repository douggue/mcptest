import { beforeEach, describe, expect, test } from 'vitest';
import { COVER_VIEWED_MIN_WIDTH, pickImage, readChannelBrand } from '../src/channel/brand';
import { openDatabase, transactionRunner } from '../src/db/sqlite';
import { SqliteBrandRepo } from '../src/repos/sqliteBrandRepo';
import { SqliteChannelRepo } from '../src/repos/sqliteChannelRepo';
import { SqliteVideoPageRepo } from '../src/repos/sqliteVideoPageRepo';
import { SqliteVideoRepo } from '../src/repos/sqliteVideoRepo';
import type { ApiVideoDetails } from '../src/sources/dataApi';
import type {
  ChannelBrand,
  ChannelSnapshot,
  StoryboardLevel,
  VideoPage,
  VideoPageOptions,
  VideoTranscript,
  YouTubeSource,
} from '../src/sources/types';
import { readVideoFrames } from '../src/video/frames';
import {
  STORYBOARD_FRESH_HOURS,
  TRANSCRIPT_NONE_RETRY_HOURS,
  readStoryboard,
  readTranscript,
  readVideoDetails,
  type VideoPageDeps,
} from '../src/video/pages';

const START = new Date('2026-11-20T12:00:00Z');
const HOUR_MS = 3_600_000;
const VIDEO = 'bArCA8xnLqU';
const OTHER = 'kmIXOl3R1Kw';
const CHANNEL = `UC${'a'.repeat(22)}`;

const transcript: VideoTranscript = {
  language: 'en',
  autoGenerated: true,
  segments: [{ startMs: 600, text: 'Right now' }],
};

const level: StoryboardLevel = {
  templateUrl: 'https://i.ytimg.com/sb/bArCA8xnLqU/storyboard3_L2/M$M.jpg?sqp=x&sigh=y',
  frameWidth: 160,
  frameHeight: 90,
  frameCount: 157,
  columns: 5,
  rows: 5,
  intervalMs: 10_000,
  sheetCount: 7,
};

const details = {
  title: 'A video',
  description: 'About it',
  tags: ['bread'],
  durationSeconds: 1554,
};

const brand: ChannelBrand = {
  description: 'We bake bread.',
  avatar: [{ url: 'https://yt3.googleusercontent.com/logo', width: 160, height: 160 }],
  banner: [],
  keywords: [],
  links: [],
};

/** A source that counts what it is asked and answers from what a test gives it. */
class FakeSource implements YouTubeSource {
  readonly pageCalls: Array<[string, boolean]> = [];
  channelCalls = 0;
  page: (videoId: string) => Omit<VideoPage, 'videoId'> = () => ({
    details,
    storyboard: [level],
    transcript,
  });
  brand: ChannelBrand | undefined = brand;

  async resolveChannelId(): Promise<string> {
    return CHANNEL;
  }

  async fetchChannel(): Promise<ChannelSnapshot> {
    this.channelCalls += 1;
    return {
      channel: {
        id: CHANNEL,
        title: 'Some Bakery',
        handle: 'somebakery',
        subscribers: 900,
        subscribersHidden: false,
        videoCount: 0,
      },
      videos: [],
      ...(this.brand ? { brand: this.brand } : {}),
    };
  }

  async getSidebar(): Promise<readonly never[]> {
    return [];
  }

  async fetchVideoPage(videoId: string, options: VideoPageOptions = {}): Promise<VideoPage> {
    this.pageCalls.push([videoId, options.transcript ?? false]);
    const { transcript: captions, ...rest } = this.page(videoId);
    return { videoId, ...rest, ...(options.transcript ? { transcript: captions ?? null } : {}) };
  }
}

let source: FakeSource;
let clock: Date;
let pages: SqliteVideoPageRepo;
let deps: VideoPageDeps;
let channelDeps: Parameters<typeof readChannelBrand>[0];

beforeEach(() => {
  const db = openDatabase(':memory:');
  source = new FakeSource();
  clock = START;
  pages = new SqliteVideoPageRepo(db);
  deps = { source, transcripts: pages, details: pages, now: () => clock };
  channelDeps = {
    source,
    channels: new SqliteChannelRepo(db),
    videos: new SqliteVideoRepo(db),
    brands: new SqliteBrandRepo(db),
    transact: transactionRunner(db),
    now: () => clock,
  };
});

const later = (hours: number): void => {
  clock = new Date(clock.getTime() + hours * HOUR_MS);
};

describe('readTranscript', () => {
  test('reads a video’s captions once and answers from the store after that', async () => {
    const first = await readTranscript(deps, VIDEO);
    later(24 * 400);
    const second = await readTranscript(deps, VIDEO);

    expect(first).toEqual({ videoId: VIDEO, transcript, fetchedAt: START, fromStore: false });
    expect(second).toEqual({ videoId: VIDEO, transcript, fetchedAt: START, fromStore: true });
    expect(source.pageCalls).toEqual([[VIDEO, true]]);
  });

  test('stores the description and the storyboard that came with the same page', async () => {
    await readTranscript(deps, VIDEO);

    expect(pages.findDetails(VIDEO)).toMatchObject({ description: 'About it', source: 'web' });
    expect(pages.findStoryboard(VIDEO)?.levels).toEqual([level]);
  });

  test('answers "none" for a video without captions, as a normal result', async () => {
    source.page = () => ({ details, storyboard: [], transcript: null });

    const result = await readTranscript(deps, VIDEO);

    expect(result).toMatchObject({ transcript: null, fromStore: false });
  });

  test('believes "none" for a day, then asks again in case captions were written since', async () => {
    source.page = () => ({ details, storyboard: [], transcript: null });
    await readTranscript(deps, VIDEO);

    later(TRANSCRIPT_NONE_RETRY_HOURS - 1);
    expect((await readTranscript(deps, VIDEO)).fromStore).toBe(true);

    source.page = () => ({ details, storyboard: [], transcript });
    later(2);
    expect(await readTranscript(deps, VIDEO)).toMatchObject({ transcript, fromStore: false });
    expect(source.pageCalls).toHaveLength(2);
  });

  test('refuses anything that is not a video id, and stores nothing when the read fails', async () => {
    await expect(readTranscript(deps, 'not a video')).rejects.toThrow(/video id/);

    source.page = () => {
      throw new Error('YouTube said no');
    };
    await expect(readTranscript(deps, VIDEO)).rejects.toThrow('YouTube said no');
    expect(pages.find(VIDEO)).toBeNull();
  });
});

describe('readStoryboard', () => {
  test('uses the stored sheets while their addresses are fresh, then reads the page again', async () => {
    expect(await readStoryboard(deps, VIDEO)).toEqual({ levels: [level], fromStore: false });

    later(STORYBOARD_FRESH_HOURS - 1);
    expect(await readStoryboard(deps, VIDEO)).toEqual({ levels: [level], fromStore: true });

    later(2);
    expect((await readStoryboard(deps, VIDEO)).fromStore).toBe(false);
    expect(source.pageCalls).toEqual([
      [VIDEO, false],
      [VIDEO, false],
    ]);
  });

  test('remembers that a video has no storyboard', async () => {
    source.page = () => ({ details, storyboard: [] });

    await readStoryboard(deps, VIDEO);

    expect(await readStoryboard(deps, VIDEO)).toEqual({ levels: [], fromStore: true });
  });
});

describe('readVideoDetails', () => {
  const fromApi = (videoId: string): ApiVideoDetails => ({
    videoId,
    title: `API title ${videoId}`,
    description: 'From the API',
    tags: ['api'],
  });

  test('reads each video’s page once, one at a time, and answers from the store after', async () => {
    const first = await readVideoDetails(deps, [VIDEO, OTHER, VIDEO]);
    const second = await readVideoDetails(deps, [OTHER, VIDEO]);

    expect(first.details.map((entry) => entry.videoId)).toEqual([VIDEO, OTHER]);
    expect(first).toMatchObject({ problems: [], apiProblem: null });
    expect(second.details.map((entry) => entry.videoId)).toEqual([OTHER, VIDEO]);
    expect(source.pageCalls).toEqual([
      [VIDEO, false],
      [OTHER, false],
    ]);
  });

  test('prefers the official API when the owner’s key is set: one request, no page read', async () => {
    const asked: string[][] = [];
    const withKey: VideoPageDeps = {
      ...deps,
      fetchDetails: async (ids) => {
        asked.push([...ids]);
        return ids.map(fromApi);
      },
    };

    const result = await readVideoDetails(withKey, [VIDEO, OTHER]);

    expect(asked).toEqual([[VIDEO, OTHER]]);
    expect(source.pageCalls).toEqual([]);
    expect(result.details[0]).toMatchObject({
      title: `API title ${VIDEO}`,
      tags: ['api'],
      source: 'api',
      durationSeconds: null,
    });
  });

  test('reads the page of a video the API did not return', async () => {
    const withKey: VideoPageDeps = { ...deps, fetchDetails: async () => [fromApi(VIDEO)] };

    const result = await readVideoDetails(withKey, [VIDEO, OTHER]);

    expect(source.pageCalls).toEqual([[OTHER, false]]);
    expect(result.details.map((entry) => entry.source)).toEqual(['api', 'web']);
  });

  test('falls back to the pages when the API refuses, and says why', async () => {
    const withKey: VideoPageDeps = {
      ...deps,
      fetchDetails: async () => {
        throw new Error('The YouTube API key has used up its daily allowance.\n  at somewhere');
      },
    };

    const result = await readVideoDetails(withKey, [VIDEO]);

    expect(result.details).toHaveLength(1);
    expect(result.apiProblem).toBe('The YouTube API key has used up its daily allowance.');
  });

  test('reports a video that could not be read and still returns the others', async () => {
    source.page = (videoId) => {
      if (videoId === OTHER) throw new Error('This video is unavailable');
      return { details, storyboard: [] };
    };

    const result = await readVideoDetails(deps, [VIDEO, OTHER]);

    expect(result.details.map((entry) => entry.videoId)).toEqual([VIDEO]);
    expect(result.problems).toEqual([{ videoId: OTHER, reason: 'This video is unavailable' }]);
  });

  test('reports a page that gave no description, and refuses a bad id before any request', async () => {
    source.page = () => ({ details: null, storyboard: [] });

    expect((await readVideoDetails(deps, [VIDEO])).problems).toEqual([
      { videoId: VIDEO, reason: 'YouTube gave no description for it' },
    ]);
    await expect(readVideoDetails(deps, [VIDEO, '../x'])).rejects.toThrow(/video id/);
    expect(source.pageCalls).toHaveLength(1);
  });
});

describe('readVideoFrames', () => {
  const jpeg = (): Response =>
    new Response(new Uint8Array([0xff, 0xd8, 1, 2]), { headers: { 'content-type': 'image/jpeg' } });

  test('returns the sheets asked for, spread across the video, each with its caption', async () => {
    const urls: string[] = [];
    const frames = await readVideoFrames(
      {
        ...deps,
        fetchImage: async (url) => {
          urls.push(url);
          return jpeg();
        },
      },
      VIDEO,
      3,
    );

    expect(frames).toMatchObject({
      videoId: VIDEO,
      sheetCount: 7,
      frameWidth: 160,
      frameHeight: 90,
    });
    expect(frames?.sheets.map((entry) => entry.sheet.index)).toEqual([0, 3, 6]);
    expect(frames?.sheets[1]?.caption).toMatch(/^Sheet 4 of 7: a grid 5 across and 5 down/);
    expect(frames?.sheets.every((entry) => entry.image.ok)).toBe(true);
    expect(urls.map((url) => new URL(url).pathname)).toEqual([
      '/sb/bArCA8xnLqU/storyboard3_L2/M0.jpg',
      '/sb/bArCA8xnLqU/storyboard3_L2/M3.jpg',
      '/sb/bArCA8xnLqU/storyboard3_L2/M6.jpg',
    ]);
  });

  test('returns sheets in a row from the one asked for, and says how many frames the video has', async () => {
    const frames = await readVideoFrames({ ...deps, fetchImage: async () => jpeg() }, VIDEO, 4, 4);

    expect(frames).toMatchObject({ sheetCount: 7, frameCount: 157 });
    expect(frames?.sheets.map((entry) => entry.sheet.index)).toEqual([4, 5, 6]);
    expect(frames?.sheets.at(-1)?.caption).toMatch(/^Sheet 7 of 7/);
  });

  test('returns no sheets, and still the totals, when asked to start past the end', async () => {
    const frames = await readVideoFrames({ ...deps, fetchImage: async () => jpeg() }, VIDEO, 4, 9);

    expect(frames).toMatchObject({ sheetCount: 7, frameCount: 157, sheets: [] });
  });

  test('has no frames for a video without a storyboard', async () => {
    source.page = () => ({ details, storyboard: [] });

    expect(await readVideoFrames(deps, VIDEO, 3)).toBeNull();
  });

  test('reports a sheet that could not be loaded beside the ones that were', async () => {
    const frames = await readVideoFrames(
      {
        ...deps,
        fetchImage: async (url) =>
          url.includes('/M0.jpg') ? new Response('', { status: 404 }) : jpeg(),
      },
      VIDEO,
      2,
    );

    expect(frames?.sheets.map((entry) => entry.image.ok)).toEqual([false, true]);
  });

  test('reads the page again when every stored sheet address has run out', async () => {
    await readStoryboard(deps, VIDEO);
    let expired = true;
    const frames = await readVideoFrames(
      {
        ...deps,
        fetchImage: async () => {
          if (expired) return new Response('', { status: 403 });
          return jpeg();
        },
        source: {
          fetchVideoPage: async (videoId, options) => {
            expired = false;
            return source.fetchVideoPage(videoId, options);
          },
        },
      },
      VIDEO,
      2,
    );

    expect(frames?.sheets.every((entry) => entry.image.ok)).toBe(true);
    expect(source.pageCalls).toHaveLength(2);
  });

  test('does not read the page twice when sheets it has just read fail to load', async () => {
    const frames = await readVideoFrames(
      { ...deps, fetchImage: async () => new Response('', { status: 403 }) },
      VIDEO,
      2,
    );

    expect(frames?.sheets.every((entry) => !entry.image.ok)).toBe(true);
    expect(source.pageCalls).toHaveLength(1);
  });
});

describe('readChannelBrand', () => {
  test('reads the channel once, stores its branding with it, and answers from the store after', async () => {
    const first = await readChannelBrand(channelDeps, '@somebakery');
    const second = await readChannelBrand(channelDeps, CHANNEL);

    expect(first).toMatchObject({ fromStore: false, channel: { id: CHANNEL } });
    expect(first.brand).toMatchObject({ description: 'We bake bread.', fetchedAt: START });
    expect(second).toMatchObject({ fromStore: true, brand: { description: 'We bake bread.' } });
    expect(source.channelCalls).toBe(1);
  });

  test('reads a channel again when it was stored before branding was kept', async () => {
    source.brand = undefined;
    await readChannelBrand(channelDeps, CHANNEL);
    source.brand = brand;

    const result = await readChannelBrand(channelDeps, CHANNEL);

    expect(result).toMatchObject({ fromStore: false, brand: { avatar: brand.avatar } });
    expect(source.channelCalls).toBe(2);
  });

  test('has no branding for a channel whose page gave none', async () => {
    source.brand = undefined;

    expect((await readChannelBrand(channelDeps, CHANNEL)).brand).toBeNull();
  });

  test('refuses anything that is not a channel', async () => {
    await expect(readChannelBrand(channelDeps, 'https://evil.example/x')).rejects.toThrow(
      /Not a valid YouTube channel/,
    );
  });
});

describe('pickImage', () => {
  const sizes = [72, 160, 900].map((width) => ({
    url: `https://x/${width}`,
    width,
    height: width,
  }));

  test('takes the smallest picture that is wide enough, else the widest', () => {
    expect(pickImage(sizes, 64)?.width).toBe(72);
    expect(pickImage(sizes, 256)?.width).toBe(900);
    expect(pickImage(sizes, COVER_VIEWED_MIN_WIDTH)?.width).toBe(900);
    expect(pickImage([], 64)).toBeNull();
  });
});
