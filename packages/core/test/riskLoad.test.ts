import { beforeEach, describe, expect, test } from 'vitest';
import { openDatabase, type Db } from '../src/db/sqlite';
import { freezeMapSnapshot } from '../src/map/snapshot';
import { SqliteChannelRepo } from '../src/repos/sqliteChannelRepo';
import { SqliteConceptRepo } from '../src/repos/sqliteConceptRepo';
import { SqliteEdgeRepo } from '../src/repos/sqliteEdgeRepo';
import { SqliteMapRepo } from '../src/repos/sqliteMapRepo';
import { SqliteRiskRepo } from '../src/repos/sqliteRiskRepo';
import { SqliteScriptRepo } from '../src/repos/sqliteScriptRepo';
import { SqliteVideoPageRepo } from '../src/repos/sqliteVideoPageRepo';
import { SqliteVideoRepo } from '../src/repos/sqliteVideoRepo';
import { riskFacts, scriptedConcepts } from '../src/risk/load';
import type { StorableVideo } from '../src/sources/types';

const NOW = new Date('2026-11-21T12:00:00Z');
const CENTER = `UC${'c'.repeat(22)}`;
const PEER = `UC${'p'.repeat(22)}`;
const NO_MAP = `UC${'n'.repeat(22)}`;

const makeRepos = (db: Db) => ({
  channels: new SqliteChannelRepo(db),
  videos: new SqliteVideoRepo(db),
  edges: new SqliteEdgeRepo(db),
  maps: new SqliteMapRepo(db),
  concepts: new SqliteConceptRepo(db),
  scripts: new SqliteScriptRepo(db),
  transcripts: new SqliteVideoPageRepo(db),
  risks: new SqliteRiskRepo(db),
});
let deps: ReturnType<typeof makeRepos>;
let conceptId: number;

const video = (channelId: string, id: string, days: number): StorableVideo => ({
  id: id.padEnd(11, '_'),
  channelId,
  title: `Title of ${id}`,
  views: 1000,
  durationSeconds: 600,
  published: { date: new Date(NOW.getTime() - days * 86_400_000), precision: 'day', raw: '' },
});

beforeEach(() => {
  deps = makeRepos(openDatabase(':memory:'));
  for (const id of [CENTER, PEER]) {
    deps.channels.upsert(
      {
        id,
        title: id,
        handle: null,
        subscribers: 1000,
        subscribersHidden: false,
        videoCount: null,
      },
      NOW,
    );
    deps.videos.upsertMany(
      [1, 2, 3, 4, 5].map((n) => video(id, `${id.slice(2, 3)}vid${n}`, 10 + n)),
      NOW,
    );
  }
  deps.maps.create(
    {
      centerChannelId: CENTER,
      depth: 1,
      region: 'US',
      members: [
        { channelId: CENTER, steps: 0 },
        { channelId: PEER, steps: 1 },
      ],
    },
    NOW,
  );
  freezeMapSnapshot(deps, CENTER, NOW);
  deps.transcripts.save(
    'pvid1______',
    {
      language: 'en',
      autoGenerated: false,
      segments: [
        { startMs: 0, text: 'the army quietly built a city under the ice and then walked away' },
      ],
    },
    NOW,
  );
  const batch = deps.concepts.createBatch(
    {
      centerChannelId: CENTER,
      inspiration: [],
      hookModels: [],
      format: null,
      angle: null,
      length: 'long',
    },
    NOW,
  );
  const [stored] = deps.concepts.addConcepts(
    batch,
    [
      {
        title: 'The Secret City Under the Ice',
        altTitles: ['A', 'B'],
        thumbnail: 'A city in a glacier',
        overlay: 'STILL THERE?',
        hook: 'h',
        hookStyle: null,
        restsOn: 'r',
        needs: 'nothing',
        origin: 'batch',
        parentId: null,
        engine: 'test',
      },
    ],
    NOW,
  );
  conceptId = stored?.id ?? 0;
  deps.concepts.setKept(CENTER, conceptId, true);
});

describe('riskFacts', () => {
  test('works out overlaps with stored look-alike transcripts and counts unchecked facts, from the tightened script', () => {
    deps.scripts.save(
      CENTER,
      conceptId,
      {
        draft: 'An older draft.',
        tightened:
          'In 1959 the army quietly built a city under the ice and then left. [CHECK: the year]\nIt cost a fortune. [CHECK: the cost]',
      },
      NOW,
    );

    const facts = riskFacts(deps, CENTER, conceptId, NOW);

    expect(facts).toMatchObject({
      status: 'ready',
      stage: 'tightened',
      title: 'The Secret City Under the Ice',
      transcriptsCompared: 1,
    });
    if (facts?.status !== 'ready') throw new Error('expected a script');
    expect(facts.overlaps.map((overlap) => [overlap.id, overlap.videoId, overlap.words])).toEqual([
      ['o1', 'pvid1______', 11],
    ]);
    expect(facts.unchecked.map((marker) => marker.what)).toEqual(['the year', 'the cost']);
  });

  test('says when there is no script or no such concept, and has nothing with no map', () => {
    expect(riskFacts(deps, CENTER, conceptId, NOW)).toEqual({ status: 'no-script' });
    expect(riskFacts(deps, CENTER, 999, NOW)).toEqual({ status: 'no-concept' });
    expect(riskFacts(deps, NO_MAP, conceptId, NOW)).toBeNull();
  });

  test('lists the kept concepts that have a script', () => {
    deps.scripts.save(CENTER, conceptId, { draft: 'Words.' }, NOW);
    expect(scriptedConcepts(deps, CENTER)).toEqual([
      { conceptId, title: 'The Secret City Under the Ice' },
    ]);
  });
});

describe('SqliteRiskRepo', () => {
  test("keeps a concept's latest checked answer", () => {
    const check = {
      claims: [{ where: 'title' as const, says: 'Secret', script: null, why: 'Not said.' }],
      notes: [{ id: 'o1', note: 'Close wording.' }],
      engine: 'claude',
      checkedAt: NOW,
      scriptUpdatedAt: NOW,
    };
    expect(deps.risks.find(CENTER, conceptId)).toBeNull();
    deps.risks.save(CENTER, conceptId, check);
    expect(deps.risks.find(CENTER, conceptId)).toEqual(check);
    expect(deps.risks.find(NO_MAP, conceptId)).toBeNull();
  });
});
