import { beforeEach, describe, expect, test } from 'vitest';
import { openDatabase, type Db } from '../src/db/sqlite';
import { SqliteBrandRepo } from '../src/repos/sqliteBrandRepo';
import { SqliteChannelRepo } from '../src/repos/sqliteChannelRepo';
import { SqliteVideoPageRepo } from '../src/repos/sqliteVideoPageRepo';
import type { ChannelBrand, StoryboardLevel, VideoTranscript } from '../src/sources/types';

const T1 = new Date('2026-11-20T12:00:00Z');
const T2 = new Date('2026-11-21T12:00:00Z');
const VIDEO = 'bArCA8xnLqU';
const CHANNEL = `UC${'a'.repeat(22)}`;

const transcript: VideoTranscript = {
  language: 'en',
  autoGenerated: true,
  segments: [
    { startMs: 600, text: 'Right now, under millions of American' },
    { startMs: 2700, text: 'tires, a crack is quietly spreading.' },
  ],
};

const level: StoryboardLevel = {
  templateUrl: 'https://i.ytimg.com/sb/bArCA8xnLqU/storyboard3_L2/M$M.jpg?sqp=x&sigh=y',
  frameWidth: 160,
  frameHeight: 90,
  frameCount: 157,
  columns: 5,
  rows: 5,
  intervalMs: 10_000,
  sheetCount: 7,
};

let db: Db;
let pages: SqliteVideoPageRepo;

beforeEach(() => {
  db = openDatabase(':memory:');
  pages = new SqliteVideoPageRepo(db);
});

describe('stored transcripts', () => {
  test('are absent until a video’s captions have been asked for', () => {
    expect(pages.find(VIDEO)).toBeNull();
  });

  test('come back as they were stored, for a video no crawl has read', () => {
    pages.save(VIDEO, transcript, T1);

    expect(pages.find(VIDEO)).toEqual({ videoId: VIDEO, transcript, fetchedAt: T1 });
  });

  test('remember that a video had no captions', () => {
    pages.save(VIDEO, null, T1);

    expect(pages.find(VIDEO)).toEqual({ videoId: VIDEO, transcript: null, fetchedAt: T1 });
  });

  test('are replaced by a later reading', () => {
    pages.save(VIDEO, null, T1);
    pages.save(VIDEO, transcript, T2);

    expect(pages.find(VIDEO)?.fetchedAt).toEqual(T2);
    expect(pages.find(VIDEO)?.transcript?.segments).toHaveLength(2);
  });

  test('read as "never asked" when the stored lines are not what was written', () => {
    pages.save(VIDEO, transcript, T1);
    db.prepare('UPDATE video_transcripts SET segments_json = ?').run('[{"startMs":"soon"}]');

    expect(pages.find(VIDEO)).toBeNull();
  });
});

describe('stored video details', () => {
  const details = {
    title: 'A video',
    description: 'What it is about',
    tags: ['bread', 'rye'],
    durationSeconds: 1554,
  };

  test('come back with where and when they were read', () => {
    pages.saveDetails(VIDEO, details, 'web', T1);

    expect(pages.findDetails(VIDEO)).toEqual({
      videoId: VIDEO,
      ...details,
      source: 'web',
      fetchedAt: T1,
    });
    expect(pages.findDetails('aaaaaaaaaaa')).toBeNull();
  });

  test('keep the length a watch page gave when the official API, which gives none, is read later', () => {
    pages.saveDetails(VIDEO, details, 'web', T1);
    pages.saveDetails(VIDEO, { ...details, tags: ['api'], durationSeconds: null }, 'api', T2);

    expect(pages.findDetails(VIDEO)).toMatchObject({
      tags: ['api'],
      durationSeconds: 1554,
      source: 'api',
    });
  });

  test('read as absent when the stored tags are not a list of words', () => {
    pages.saveDetails(VIDEO, details, 'web', T1);
    db.prepare('UPDATE video_details SET tags_json = ?').run('{"not":"a list"}');

    expect(pages.findDetails(VIDEO)).toBeNull();
  });
});

describe('stored storyboards', () => {
  test('come back with when they were read, and an empty one means the video has none', () => {
    pages.saveStoryboard(VIDEO, [level], T1);
    pages.saveStoryboard('aaaaaaaaaaa', [], T1);

    expect(pages.findStoryboard(VIDEO)).toEqual({ levels: [level], fetchedAt: T1 });
    expect(pages.findStoryboard('aaaaaaaaaaa')).toEqual({ levels: [], fetchedAt: T1 });
    expect(pages.findStoryboard('bbbbbbbbbbb')).toBeNull();
  });

  test('read as absent when a stored sheet address is not on the image host', () => {
    pages.saveStoryboard(VIDEO, [level], T1);
    db.prepare('UPDATE video_storyboards SET levels_json = ?').run(
      JSON.stringify([{ ...level, templateUrl: 'https://evil.example/sb/M$M.jpg' }]),
    );

    expect(pages.findStoryboard(VIDEO)).toBeNull();
  });
});

describe('stored channel branding', () => {
  const brand: ChannelBrand = {
    description: 'We bake bread.',
    avatar: [{ url: 'https://yt3.googleusercontent.com/logo=s160', width: 160, height: 160 }],
    banner: [{ url: 'https://yt3.googleusercontent.com/cover=w1060', width: 1060, height: 175 }],
    keywords: ['bread', 'sourdough starter'],
    links: ['somebakery.example'],
  };
  let brands: SqliteBrandRepo;
  let channels: SqliteChannelRepo;

  beforeEach(() => {
    brands = new SqliteBrandRepo(db);
    channels = new SqliteChannelRepo(db);
    channels.upsert(
      {
        id: CHANNEL,
        title: 'Some Bakery',
        handle: 'somebakery',
        subscribers: 900,
        subscribersHidden: false,
        videoCount: 12,
      },
      T1,
    );
  });

  test('is absent until it has been read', () => {
    expect(brands.find(CHANNEL)).toBeNull();
  });

  test('comes back as stored, and survives the channel being read again', () => {
    brands.save(CHANNEL, brand, T1);
    channels.upsert({ ...channels.findById(CHANNEL)!, subscribers: 950 }, T2);

    expect(brands.find(CHANNEL)).toEqual({ channelId: CHANNEL, ...brand, fetchedAt: T1 });
  });

  test('does nothing for a channel that is not in the store', () => {
    brands.save(`UC${'z'.repeat(22)}`, brand, T1);

    expect(brands.find(`UC${'z'.repeat(22)}`)).toBeNull();
  });

  test('drops a stored picture whose address is not on the channel image host', () => {
    brands.save(CHANNEL, brand, T1);
    db.prepare('UPDATE channels SET avatar_json = ? WHERE id = ?').run(
      JSON.stringify([{ url: 'https://evil.example/logo.png', width: 160, height: 160 }]),
      CHANNEL,
    );

    expect(brands.find(CHANNEL)?.avatar).toEqual([]);
    expect(brands.find(CHANNEL)?.banner).toHaveLength(1);
  });
});
