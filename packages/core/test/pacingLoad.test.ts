import { beforeEach, describe, expect, test } from 'vitest';
import { openDatabase } from '../src/db/sqlite';
import { freezeMapSnapshot } from '../src/map/snapshot';
import { loadPacing } from '../src/pacing/load';
import { SqliteChannelRepo } from '../src/repos/sqliteChannelRepo';
import { SqliteEdgeRepo } from '../src/repos/sqliteEdgeRepo';
import { SqliteMapRepo } from '../src/repos/sqliteMapRepo';
import { SqliteVideoPageRepo } from '../src/repos/sqliteVideoPageRepo';
import { SqliteVideoRepo } from '../src/repos/sqliteVideoRepo';
import type { StorableVideo } from '../src/sources/types';

const NOW = new Date('2026-11-21T12:00:00Z');
const DAY_MS = 86_400_000;
const daysAgo = (days: number) => new Date(NOW.getTime() - days * DAY_MS);
const CENTER = `UC${'c'.repeat(22)}`;
const PEER = `UC${'p'.repeat(22)}`;
const NO_MAP = `UC${'n'.repeat(22)}`;

const makeRepos = (db: ReturnType<typeof openDatabase>) => ({
  channels: new SqliteChannelRepo(db),
  videos: new SqliteVideoRepo(db),
  edges: new SqliteEdgeRepo(db),
  maps: new SqliteMapRepo(db),
  transcripts: new SqliteVideoPageRepo(db),
});
let deps: ReturnType<typeof makeRepos>;

const video = (
  channelId: string,
  id: string,
  views: number,
  days: number,
  seconds: number,
): StorableVideo => ({
  id: id.padEnd(11, '_'),
  channelId,
  title: `Title of ${id}`,
  views,
  durationSeconds: seconds,
  published: { date: daysAgo(days), precision: 'day', raw: `${days}d ago` },
});

beforeEach(() => {
  deps = makeRepos(openDatabase(':memory:'));
  for (const [id, title] of [
    [CENTER, 'Mine'],
    [PEER, 'Peer'],
  ] as const) {
    deps.channels.upsert(
      { id, title, handle: null, subscribers: 1000, subscribersHidden: false, videoCount: null },
      NOW,
    );
  }
  deps.videos.upsertMany(
    [video(CENTER, 'mine1', 500, 10, 480), video(CENTER, 'mine2', 500, 20, 600)],
    NOW,
  );
  deps.videos.upsertMany(
    [
      ...[1, 2, 3, 4, 5].map((n) => video(PEER, `old${n}`, 1000, 40 + n, 600)),
      video(PEER, 'hit', 50_000, 6, 1200),
    ],
    NOW,
  );
  deps.maps.create(
    {
      centerChannelId: CENTER,
      depth: 1,
      region: 'US',
      members: [
        { channelId: CENTER, steps: 0 },
        { channelId: PEER, steps: 1 },
      ],
    },
    NOW,
  );
  freezeMapSnapshot(deps, CENTER, NOW);
});

describe('loadPacing', () => {
  test("compares the channel's lengths and pace with its look-alikes' breakouts", () => {
    deps.transcripts.save(
      'mine1______',
      {
        language: 'en',
        autoGenerated: true,
        segments: [
          { startMs: 0, text: Array.from({ length: 300 }, () => 'w').join(' ') },
          { startMs: 120_000, text: 'end' },
        ],
      },
      NOW,
    );

    const pacing = loadPacing(deps, CENTER, NOW);

    expect(pacing?.lengths.own).toMatchObject({ count: 2, median: 540 });
    expect(pacing?.lengths.winners).toMatchObject({ count: 1, median: 1200 });
    expect(pacing?.wordsPerMinute.own).toMatchObject({ count: 1, median: 151 });
    expect(pacing?.wordsPerMinute.winners.count).toBe(0);
    expect(pacing?.rule).toEqual({ minScore: 2, windowDays: 30, perChannel: 4 });
    expect(pacing?.lookalikes).toBe(1);
  });

  test('has nothing for a channel with no map', () => {
    expect(loadPacing(deps, NO_MAP, NOW)).toBeNull();
  });
});
