import { describe, expect, test } from 'vitest';
import {
  mapStoryboard,
  mapTranscriptPanel,
  mapVideoDetails,
  parseTimedText,
  pickCaptionTrack,
} from '../src/sources/videoPage';
import timedText from './fixtures/timedtext.json';
import page from './fixtures/video-page.json';

describe('mapVideoDetails', () => {
  test('reads the title, description and length a watch page gives', () => {
    const details = mapVideoDetails(page.basic_info);

    expect(details).toMatchObject({
      title: "America's New Material Could END POTHOLES Forever!",
      tags: [],
      durationSeconds: 1554,
    });
    expect(details?.description).toMatch(/^America's roads are falling apart/);
  });

  test('reads the tags, whichever of the two names they come under', () => {
    const base = { title: 'A video', short_description: 'About it', duration: 61 };

    expect(mapVideoDetails({ ...base, keywords: ['bread', 'sourdough'] })?.tags).toEqual([
      'bread',
      'sourdough',
    ]);
    expect(mapVideoDetails({ ...base, tags: ['rye'] })?.tags).toEqual(['rye']);
  });

  test('keeps untrusted text within bounds', () => {
    const details = mapVideoDetails({
      title: 'T',
      short_description: 'x'.repeat(20_000),
      keywords: [...Array.from({ length: 200 }, (_, n) => `tag ${n}`), 7, 'y'.repeat(900)],
    });

    expect(details?.description).toHaveLength(5000);
    expect(details?.tags).toHaveLength(60);
    expect(details?.tags.every((tag) => tag.length <= 100)).toBe(true);
  });

  test('has no details for a page that gave neither a title nor a description', () => {
    expect(mapVideoDetails({ id: 'bArCA8xnLqU' })).toBeNull();
    expect(mapVideoDetails(null)).toBeNull();
  });
});

describe('mapStoryboard', () => {
  test('reads each size with its grid, interval and sheet address', () => {
    const levels = mapStoryboard(page.storyboards);

    expect(levels).toHaveLength(3);
    expect(levels[2]).toMatchObject({
      frameWidth: 160,
      frameHeight: 90,
      frameCount: 157,
      columns: 5,
      rows: 5,
      intervalMs: 10_000,
      sheetCount: 7,
    });
    expect(levels[2]?.templateUrl).toMatch(
      /^https:\/\/i\.ytimg\.com\/sb\/bArCA8xnLqU\/storyboard3_L2\/M\$M\.jpg\?/,
    );
  });

  const board = (overrides: Record<string, unknown> = {}) => ({
    type: 'vod',
    template_url: 'https://i.ytimg.com/sb/abc/storyboard3_L2/M$M.jpg?sqp=x&sigh=y',
    thumbnail_width: 160,
    thumbnail_height: 90,
    thumbnail_count: 40,
    interval: 5000,
    columns: 5,
    rows: 5,
    storyboard_count: 2,
    ...overrides,
  });

  test.each([
    ['an address on another host', { template_url: 'https://evil.example/sb/abc/M$M.jpg' }],
    ['an address outside the storyboard folder', { template_url: 'https://i.ytimg.com/vi/x.jpg' }],
    ['a size of nothing', { thumbnail_width: 0 }],
    ['a grid of nothing', { columns: 0 }],
    ['an absurd number of sheets', { storyboard_count: 100_000 }],
    ['a live stream’s storyboard', { type: 'live' }],
  ])('leaves out a size with %s', (_what, overrides) => {
    expect(mapStoryboard({ boards: [board(overrides), board()] })).toHaveLength(1);
  });

  test('has none for a page without a storyboard', () => {
    expect(mapStoryboard(undefined)).toEqual([]);
    expect(mapStoryboard({ boards: 'nope' })).toEqual([]);
  });
});

describe('pickCaptionTrack', () => {
  test('picks the captions of the original audio, asked for as JSON', () => {
    const track = pickCaptionTrack(page.captions);

    expect(track).toMatchObject({ language: 'en', autoGenerated: true });
    const url = new URL(track?.url ?? '');
    expect(`${url.origin}${url.pathname}`).toBe('https://www.youtube.com/api/timedtext');
    expect(url.searchParams.get('lang')).toBe('en');
    expect(url.searchParams.get('fmt')).toBe('json3');
  });

  const track = (language: string, overrides: Record<string, unknown> = {}) => ({
    base_url: `https://www.youtube.com/api/timedtext?v=abc&lang=${language}`,
    language_code: language,
    ...overrides,
  });

  test('takes the first track when the page does not say which is the original', () => {
    expect(pickCaptionTrack({ caption_tracks: [track('de'), track('en')] })).toMatchObject({
      language: 'de',
      autoGenerated: false,
    });
  });

  test('never takes a track whose address is not YouTube’s own caption address', () => {
    const elsewhere = track('en', { base_url: 'https://evil.example/api/timedtext?lang=en' });
    const otherPath = track('fr', { base_url: 'https://www.youtube.com/watch?v=abc' });

    expect(pickCaptionTrack({ caption_tracks: [elsewhere, otherPath] })).toBeNull();
    expect(pickCaptionTrack({ caption_tracks: [elsewhere, track('es')] })?.language).toBe('es');
  });

  test('has none for a video without captions', () => {
    expect(pickCaptionTrack(undefined)).toBeNull();
    expect(pickCaptionTrack({ caption_tracks: [] })).toBeNull();
  });
});

describe('parseTimedText', () => {
  test('joins each caption line’s words and keeps when it starts', () => {
    const segments = parseTimedText(timedText);

    expect(segments.slice(0, 3)).toEqual([
      { startMs: 600, text: 'Right now, under millions of American' },
      { startMs: 2700, text: 'tires, a crack is quietly spreading.' },
      { startMs: 5600, text: expect.stringMatching(/^Almost nobody driving over it knows why/) },
    ]);
    // Events that only open a window or break a line carry no words.
    expect(segments.every((segment) => segment.text.trim().length > 0)).toBe(true);
  });

  test('reads nothing from an answer of another shape', () => {
    expect(parseTimedText({ events: 'nope' })).toEqual([]);
    expect(parseTimedText('<html>')).toEqual([]);
    expect(parseTimedText({ events: [{ tStartMs: -5, segs: [{ utf8: 'x' }] }, null] })).toEqual([]);
  });
});

describe('mapTranscriptPanel', () => {
  const segment = (startMs: string, text: string) => ({
    type: 'TranscriptSegment',
    start_ms: startMs,
    snippet: { text },
  });

  test('reads the lines of the transcript panel and its language', () => {
    const panel = {
      selectedLanguage: 'English (auto-generated)',
      transcript: {
        content: {
          body: {
            initial_segments: [
              segment('0', 'Right now'),
              { type: 'TranscriptSectionHeader' },
              segment('2700', 'a crack is spreading'),
            ],
          },
        },
      },
    };

    expect(mapTranscriptPanel(panel)).toEqual({
      language: 'English (auto-generated)',
      autoGenerated: true,
      segments: [
        { startMs: 0, text: 'Right now' },
        { startMs: 2700, text: 'a crack is spreading' },
      ],
    });
  });

  test('has no transcript when the panel holds no line', () => {
    expect(
      mapTranscriptPanel({ transcript: { content: { body: { initial_segments: [] } } } }),
    ).toBe(null);
    expect(mapTranscriptPanel(undefined)).toBeNull();
  });
});
