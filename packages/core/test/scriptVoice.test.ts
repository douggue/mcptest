import { describe, expect, test } from 'vitest';
import { figuresWithoutCheck } from '../src/script/measure';
import type { VideoTranscript } from '../src/sources/types';
import {
  LENGTH_MIN_VIDEOS,
  SHORTS_MAX_SECONDS,
  VOICE_VIDEOS,
  lengthRange,
  voiceProfile,
} from '../src/script/voice';

/** Captions of `words` words spread evenly over `seconds`, with or without sentence ends. */
function captions(words: number, seconds: number, sentenceWords: number | null): VideoTranscript {
  const lines = 10;
  const perLine = words / lines;
  const segments = Array.from({ length: lines + 1 }, (_, index) => {
    const said = Array.from({ length: index === lines ? 0 : perLine }, (_w, at) => {
      const position = index * perLine + at + 1;
      const ends = sentenceWords !== null && position % sentenceWords === 0;
      return ends ? 'word.' : 'word';
    });
    return { startMs: (index * seconds * 1000) / lines, text: said.join(' ') || 'end.' };
  });
  return { language: 'en', autoGenerated: sentenceWords === null, segments };
}

describe('a channel’s voice, from its own captions', () => {
  test('is measured over its five best videos', () => {
    expect(VOICE_VIDEOS).toBe(5);
  });

  test('gives the middle pace, the typical sentence and the reading grade of what was said', () => {
    const profile = voiceProfile([
      captions(300, 120, 10),
      captions(320, 120, 10),
      captions(400, 120, 20),
    ]);

    expect(profile.videos).toBe(3);
    // 301, 321 and 401 words over two minutes: 151, 161 and 201 a minute; the middle one is taken.
    expect(profile.wordsPerMinute).toBe(161);
    expect(profile.sentenceWords).toBe(10);
    expect(profile.punctuated).toBe(3);
    expect(profile.grade).not.toBeNull();
  });

  test('gives a pace but no sentence length or grade when the captions carry no sentence ends', () => {
    const profile = voiceProfile([captions(300, 120, null), captions(300, 120, null)]);

    expect(profile.wordsPerMinute).toBe(151);
    expect(profile).toMatchObject({ videos: 2, punctuated: 0, sentenceWords: null, grade: null });
  });

  test('measures sentences on the punctuated captions only', () => {
    const profile = voiceProfile([captions(300, 120, null), captions(300, 120, 15)]);

    expect(profile).toMatchObject({ videos: 2, punctuated: 1, sentenceWords: 15 });
  });

  test('is unknown without captions', () => {
    expect(voiceProfile([])).toEqual({
      videos: 0,
      punctuated: 0,
      wordsPerMinute: null,
      sentenceWords: null,
      grade: null,
    });
  });
});

describe('how long a video may be', () => {
  test('is taken from the lengths of the look-alikes’ winners, Shorts left out', () => {
    const minutes = [4, 8, 9, 10, 11, 12, 14, 15, 16, 40].map((value) => value * 60);

    expect(SHORTS_MAX_SECONDS).toBe(60);
    expect(lengthRange([...minutes, 30, 45, 58])).toEqual({
      minSeconds: 8 * 60,
      maxSeconds: 16 * 60,
      typicalSeconds: 11.5 * 60,
      videos: 10,
    });
  });

  test('is the shortest to the longest when there are only a few winners', () => {
    expect(lengthRange([300, 900, 600])).toEqual({
      minSeconds: 300,
      maxSeconds: 900,
      typicalSeconds: 600,
      videos: 3,
    });
  });

  test('is unknown with fewer winners than can show a range', () => {
    expect(LENGTH_MIN_VIDEOS).toBe(3);
    expect(lengthRange([300, 900])).toBeNull();
    expect(lengthRange([20, 30, 40, 50])).toBeNull();
  });
});

describe('sentences with a figure and no check marker', () => {
  test('are listed, so a number nobody marked is not missed', () => {
    const script = [
      '## HOOK',
      '[B-ROLL: a plant in 1987 | old plant | ]',
      'The plant closed in 1987 [CHECK: the year]. It had 400 workers. Nobody knows why.',
      'It cost $2 million, they say [CHECK: the cost], and ran for forty years.',
    ].join('\n');

    expect(figuresWithoutCheck(script)).toEqual(['It had 400 workers.']);
  });

  test('are none in a script with no figures', () => {
    expect(figuresWithoutCheck('Nobody knows why. It still runs.')).toEqual([]);
  });
});
