import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, test } from 'vitest';
import { openDatabase } from '../src/db/sqlite';
import {
  TRANSCRIPT_FILES_MAX,
  saveChannelTranscripts,
  type TranscriptDownloadDeps,
} from '../src/downloads/transcripts';
import { DEFAULT_WINNERS_PER_CHANNEL } from '../src/map/thumbnails';
import { SqliteChannelRepo } from '../src/repos/sqliteChannelRepo';
import { SqliteVideoPageRepo } from '../src/repos/sqliteVideoPageRepo';
import { SqliteVideoRepo } from '../src/repos/sqliteVideoRepo';
import type { StorableVideo, VideoPage, VideoTranscript } from '../src/sources/types';

const NOW = new Date('2026-11-20T12:00:00Z');
const DAY_MS = 86_400_000;
const CHANNEL = `UC${'a'.repeat(22)}`;
const vid = (n: number) => `video${String(n).padStart(6, '0')}`;

const video = (n: number, views: number, daysAgo: number): StorableVideo => ({
  id: vid(n),
  channelId: CHANNEL,
  title: `Video ${n}`,
  views,
  durationSeconds: 600,
  published: { date: new Date(NOW.getTime() - daysAgo * DAY_MS), precision: 'day', raw: 'x' },
});

const captions = (words: string): VideoTranscript => ({
  language: 'en',
  autoGenerated: true,
  segments: [
    { startMs: 0, text: words },
    { startMs: 60_000, text: 'and that is how it ends' },
  ],
});

let root: string;
let deps: TranscriptDownloadDeps;
let pages: SqliteVideoPageRepo;
let asked: string[];
let page: (videoId: string) => Omit<VideoPage, 'videoId'>;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'jgtube-transcripts-'));
  const db = openDatabase(':memory:');
  const channels = new SqliteChannelRepo(db);
  const videos = new SqliteVideoRepo(db);
  pages = new SqliteVideoPageRepo(db);
  channels.upsert(
    {
      id: CHANNEL,
      title: 'Some Bakery',
      handle: 'somebakery',
      subscribers: 900,
      subscribersHidden: false,
      videoCount: 6,
    },
    NOW,
  );
  // Two far above the channel's usual thousand views, four at it.
  videos.upsertMany(
    [
      video(1, 50_000, 10),
      video(2, 9000, 12),
      video(3, 1000, 14),
      video(4, 1000, 16),
      video(5, 1000, 18),
      video(6, 1000, 20),
    ],
    NOW,
  );
  asked = [];
  page = (videoId) => ({
    details: null,
    storyboard: [],
    transcript: captions(`this is what ${videoId} says`),
  });
  deps = {
    channels,
    videos,
    transcripts: pages,
    details: pages,
    now: () => NOW,
    source: {
      fetchVideoPage: async (videoId) => {
        asked.push(videoId);
        return { videoId, ...page(videoId) };
      },
    },
  };
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('saveChannelTranscripts', () => {
  test('saves as many as the thumbnail download saves winners', () => {
    expect(TRANSCRIPT_FILES_MAX).toBe(DEFAULT_WINNERS_PER_CHANNEL);
  });

  test('saves the captions of the channel’s videos that took off, one text file each', async () => {
    const result = await saveChannelTranscripts(deps, CHANNEL, root);

    const folder = join(root, 'transcripts', 'Some Bakery');
    expect(result).toMatchObject({
      channelId: CHANNEL,
      channelTitle: 'Some Bakery',
      folder,
      indexFile: join(folder, 'index.json'),
      noCaptions: [],
      failed: [],
    });
    expect(result?.saved.map((entry) => entry.videoId)).toEqual([vid(1), vid(2)]);
    expect(readdirSync(folder).sort()).toEqual(['index.json', `${vid(1)}.txt`, `${vid(2)}.txt`]);
    expect(readFileSync(join(folder, `${vid(1)}.txt`), 'utf8')).toBe(
      [
        'Video 1',
        `https://www.youtube.com/watch?v=${vid(1)}`,
        'Captions: en (auto-generated) · 11 words · last line at 1:00',
        '',
        `[0:00] this is what ${vid(1)} says`,
        '[1:00] and that is how it ends',
        '',
      ].join('\n'),
    );
  });

  test('writes an index saying what each file is', async () => {
    const result = await saveChannelTranscripts(deps, CHANNEL, root);

    const index = JSON.parse(readFileSync(result?.indexFile ?? '', 'utf8')) as {
      transcripts: Array<Record<string, unknown>>;
    };
    expect(index).toMatchObject({
      channelId: CHANNEL,
      channelTitle: 'Some Bakery',
      savedAt: '2026-11-20T12:00:00.000Z',
      winnerMinScore: 2,
      noCaptions: [],
      failed: [],
    });
    expect(index.transcripts[0]).toMatchObject({
      videoId: vid(1),
      title: 'Video 1',
      views: 50_000,
      file: `${vid(1)}.txt`,
      language: 'en',
      autoGenerated: true,
      words: 11,
    });
    expect(index.transcripts[0]?.['score']).toBeGreaterThan(10);
  });

  test('uses the stored transcript when there is one, and asks YouTube for the rest', async () => {
    pages.save(vid(1), captions('kept from before'), NOW);

    const result = await saveChannelTranscripts(deps, CHANNEL, root);

    expect(asked).toEqual([vid(2)]);
    expect(readFileSync(join(result?.folder ?? '', `${vid(1)}.txt`), 'utf8')).toContain(
      '[0:00] kept from before',
    );
  });

  test('names a video without captions instead of writing an empty file', async () => {
    page = (videoId) => ({
      details: null,
      storyboard: [],
      transcript: videoId === vid(2) ? null : captions('words'),
    });

    const result = await saveChannelTranscripts(deps, CHANNEL, root);

    expect(result?.saved.map((entry) => entry.videoId)).toEqual([vid(1)]);
    expect(result?.noCaptions).toEqual([{ videoId: vid(2), title: 'Video 2' }]);
    expect(readdirSync(result?.folder ?? '')).not.toContain(`${vid(2)}.txt`);
  });

  test('reports a video that could not be read and still saves the others', async () => {
    const fetchVideoPage = deps.source.fetchVideoPage;
    deps = {
      ...deps,
      source: {
        fetchVideoPage: async (videoId, options) => {
          if (videoId === vid(1)) throw new Error('YouTube did not answer\nstack');
          return fetchVideoPage(videoId, options);
        },
      },
    };

    const result = await saveChannelTranscripts(deps, CHANNEL, root);

    expect(result?.failed).toEqual([{ videoId: vid(1), reason: 'YouTube did not answer' }]);
    expect(result?.saved.map((entry) => entry.videoId)).toEqual([vid(2)]);
  });

  test('saves fewer when asked to', async () => {
    const result = await saveChannelTranscripts(deps, CHANNEL, root, { max: 1 });

    expect(result?.saved.map((entry) => entry.videoId)).toEqual([vid(1)]);
    expect(asked).toEqual([vid(1)]);
  });

  test('has nothing to save for a channel that is not stored, and refuses a bad id', async () => {
    expect(await saveChannelTranscripts(deps, `UC${'z'.repeat(22)}`, root)).toBeNull();
    await expect(saveChannelTranscripts(deps, '../../outside', root)).rejects.toThrow(/channel id/);
    expect(readdirSync(root)).toEqual([]);
  });

  test('writes only the index for a channel where nothing has taken off', async () => {
    const quiet = { ...deps, videos: { ...deps.videos, listByChannel: () => [] } };

    const result = await saveChannelTranscripts(quiet, CHANNEL, root);

    expect(result).toMatchObject({ saved: [], noCaptions: [], failed: [] });
    expect(readdirSync(result?.folder ?? '')).toEqual(['index.json']);
  });
});
