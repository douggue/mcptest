/**
 * The tools that read one video or one channel closely: a transcript, frames
 * across a video, a channel's branding, and videos' descriptions and tags.
 * Each reads the store first; what is missing is fetched from YouTube once,
 * through the rate limiter, and kept.
 */

type Content = CallToolResult['content'];

const SECOND_MS = 1000;
/** A bio longer than this is cut: the opening lines are what a visitor reads. */
const MAX_BIO_CHARS = 2000;

/** The video id a tool was given, as an id or a link; fails with the rule otherwise. */
function videoIdOf(video: string): string {
  try {
    return parseVideoRef(video);
  } catch {
    throw new ToolFailure(VIDEO_RULE);
  }
}

const headed = (head: Record<string, unknown>, rest: Content = []): CallToolResult => ({
  content: [...(jsonResult(head).content as Content), ...rest],
});

/** One video's captions as text with a time mark every half minute or so. */
export async function getTranscript(
  engine: ConnectorEngine,
  input: GetTranscriptArgs,
): Promise<CallToolResult> {
  const args = checkedArgs(getTranscriptArgs, input);
  const video = videoIdOf(args.video);
  const { transcript } = await engine.readTranscript(video);
  if (transcript === null) {
    return headed({ video, captions: false, note: 'YouTube lists no captions for this video.' });
  }
  const fromMs = (args.start_seconds ?? 0) * SECOND_MS;
  const { text, cutAtMs, endsAtMs } = formatTranscript(transcript.segments, {
    maxChars: args.max_chars ?? DEFAULT_TRANSCRIPT_CHARS,
    fromMs,
  });
  const cutAt = cutAtMs === null ? null : clock(cutAtMs);
  const startSeconds = cutAtMs === null ? 0 : Math.floor(cutAtMs / SECOND_MS);
  // Counted over the whole transcript, whatever part of it this answer holds.
  const pace = transcriptPace(transcript.segments);
  const head = withoutAbsent({
    video,
    lang: transcript.language,
    auto: transcript.autoGenerated ? true : null,
    lines: transcript.segments.length,
    lastLineAt: endsAtMs === null ? null : clock(endsAtMs),
    words: pace.words > 0 ? pace.words : null,
    wordsPerMinute: pace.wordsPerMinute,
    from: fromMs > 0 ? clock(fromMs) : null,
    note: text === '' ? `Nothing is said after ${clock(fromMs)}.` : null,
    cut: cutAt
      ? {
          at: cutAt,
          startSeconds,
          note: `Cut at ${cutAt} to fit max_chars. Call again with start_seconds ${startSeconds} for the rest.`,
        }
      : null,
  });
  return headed(head, text === '' ? [] : [{ type: 'text', text }]);
}

const SAMPLE_NOTE =
  'These sheets are a sample spread across the video. To see every frame, call with start_sheet 1 and follow next.';

/**
 * Where a run of sheets sits in the video: the first and last sheet it holds
 * (counted from 1), and either the sheet to ask for next or that this is the
 * last, so a reader cannot take part of a video for the whole of it.
 */
function placeOf(frames: VideoFrames, startSheet: number | undefined): Record<string, unknown> {
  if (startSheet === undefined) {
    return frames.sheets.length < frames.sheetCount ? { note: SAMPLE_NOTE } : {};
  }
  const last = frames.sheets.at(-1);
  if (last === undefined) {
    return {
      last: true,
      note: `There is no sheet ${startSheet}: the video has ${frames.sheetCount}.`,
    };
  }
  const to = last.sheet.index + 1;
  return {
    from: startSheet,
    to,
    ...(to >= frames.sheetCount
      ? { last: true }
      : {
          next: {
            start_sheet: to + 1,
            note: `You have seen sheets ${startSheet} to ${to} of ${frames.sheetCount}. Call again with start_sheet ${to + 1}.`,
          },
        }),
  };
}

/**
 * Sheets of frames of one video, each under the caption that says how to read
 * it: a sample spread across the video, or, with start_sheet, in a row so
 * that every frame can be gone through.
 */
export async function viewVideoFrames(
  engine: ConnectorEngine,
  input: ViewVideoFramesArgs,
): Promise<CallToolResult> {
  const args = checkedArgs(viewVideoFramesArgs, input);
  const video = videoIdOf(args.video);
  const frames = await engine.readVideoFrames(
    video,
    args.sheets ?? DEFAULT_FRAME_SHEETS,
    args.start_sheet === undefined ? undefined : args.start_sheet - 1,
  );
  if (frames === null) {
    return headed({
      video,
      frames: false,
      note: 'YouTube has no storyboard of frames for this video.',
    });
  }
  const shown = frames.sheets.filter((entry) => entry.image.ok).length;
  const pictures = frames.sheets.flatMap((entry): Content => {
    if (entry.image.ok) return [{ type: 'text', text: entry.caption }, imageBlock(entry.image)];
    const which = `Sheet ${entry.sheet.index + 1} of ${frames.sheetCount}`;
    return [{ type: 'text', text: `${which} could not be shown: ${entry.image.reason}` }];
  });
  const result = headed(
    {
      video,
      source: FRAME_SOURCE_NOTE[frames.source],
      sheets: frames.sheets.length,
      shown,
      ofSheets: frames.sheetCount,
      frames: frames.frameCount,
      frame: `${frames.frameWidth}x${frames.frameHeight}`,
      ...placeOf(frames, args.start_sheet),
    },
    pictures,
  );
  // Asking past the last sheet is answered, not failed: the answer says the video is over.
  return shown > 0 || frames.sheets.length === 0 ? result : { ...result, isError: true };
}

/** One of a channel's pictures as content: the picture under a line naming it, or why it is not shown. */
async function brandPicture(
  label: string,
  image: BrandImage | null,
  fetchImage: FetchImage | undefined,
): Promise<Content> {
  if (image === null) return [];
  const fetched = await fetchPinnedImage(image.url, CHANNEL_IMAGE_RULE, fetchImage);
  return fetched.ok
    ? [{ type: 'text', text: `${label}:` }, imageBlock(fetched)]
    : [{ type: 'text', text: `${label} could not be shown: ${fetched.reason}` }];
}

const sizeOf = (image: BrandImage | null): string | false =>
  image ? `${image.width}x${image.height}` : false;

/** A channel's bio, keywords and links as text, then its logo and cover as pictures. */
export async function getChannelBrand(
  engine: ConnectorEngine,
  fetchImage: FetchImage | undefined,
  input: GetChannelBrandArgs,
): Promise<CallToolResult> {
  const args = checkedArgs(getChannelBrandArgs, input);
  requireChannelRef(args.channel);
  const { channel, brand } = await engine.readChannelBrand(args.channel);
  const who = withoutAbsent({
    id: channel.id,
    title: channel.title,
    handle: channel.handle,
    subs: channel.subscribers,
  });
  if (brand === null) {
    return headed({ ...who, branding: false, note: 'Its page gave no branding to read.' });
  }
  const logo = pickImage(brand.avatar, LOGO_VIEWED_MIN_WIDTH);
  const cover = pickImage(brand.banner, COVER_VIEWED_MIN_WIDTH);
  const bio = brand.description ?? '';
  const head = {
    ...who,
    bio: bio.slice(0, MAX_BIO_CHARS),
    ...(bio.length > MAX_BIO_CHARS ? { bioCut: true } : {}),
    ...(brand.keywords.length > 0 ? { keywords: brand.keywords } : {}),
    ...(brand.links.length > 0 ? { links: brand.links } : {}),
    logo: sizeOf(logo),
    cover: sizeOf(cover),
  };
  if (args.images === false) return headed(head);
  const pictures = await Promise.all([
    brandPicture(`Logo of ${channel.title}`, logo, fetchImage),
    brandPicture(`Cover of ${channel.title}`, cover, fetchImage),
  ]);
  return headed(head, pictures.flat());
}

function videoEntry(video: VideoFacts, maxChars: number): Record<string, unknown> {
  return withoutAbsent({
    video: video.videoId,
    title: video.title,
    description: video.description.slice(0, maxChars),
    descriptionCut: video.description.length > maxChars ? true : null,
    tags: video.tags,
    secs: video.durationSeconds,
    views: video.views,
    score: video.score === null ? null : oneDecimal(video.score),
    channelId: video.channelId,
  });
}

/** The title, description, tags, length, views and score of up to ten videos. */
export async function getVideoDetails(
  engine: ConnectorEngine,
  input: GetVideoDetailsArgs,
): Promise<CallToolResult> {
  const args = checkedArgs(getVideoDetailsArgs, input);
  const answer = await engine.readVideoDetails([...new Set(args.video_ids)]);
  if (answer.videos.length === 0) {
    const reasons = answer.problems.map((problem) => `${problem.videoId}: ${problem.reason}`);
    throw new ToolFailure(`None of those videos could be read. ${reasons.join('; ')}`);
  }
  const maxChars = args.description_chars ?? DEFAULT_DESCRIPTION_CHARS;
  return jsonResult({
    shown: answer.videos.length,
    videos: answer.videos.map((video) => videoEntry(video, maxChars)),
    ...(answer.problems.length > 0
      ? {
          problems: answer.problems.map((problem) => ({
            video: problem.videoId,
            reason: problem.reason,
          })),
        }
      : {}),
    ...(answer.apiProblem
      ? {
          note: `The official API could not be used (${answer.apiProblem}), so each video’s own page was read.`,
        }
      : {}),
  });
}
