describe('the three stages', () => {
  beforeEach(() => {
    pages.save(vid('voice1'), spoken(), NOW);
    engine.openScript(MINE, conceptId);
  });

  test('with marking facts turned off, the stage is told so and the view says so', async () => {
    const quiet = lab({ ...deps, markFacts: () => false });

    const outcome = await quiet.runScriptStage('hooks', MINE, conceptId, 'claude', () => {});

    expect(asked).toEqual([
      {
        analysis: 'script-hooks',
        focus: { kind: 'script', conceptId, markFacts: false },
        only: 'claude',
      },
    ]);
    expect(outcome.view.markFacts).toBe(false);
    expect(engine.findScriptView(MINE, conceptId)?.markFacts).toBe(true);
  });

  test('hooks: asks by the concept’s number and stores three hooks and the beats', async () => {
    const outcome = await engine.runScriptStage('hooks', MINE, conceptId, 'claude', () => {});

    expect(asked).toEqual([
      { analysis: 'script-hooks', focus: { kind: 'script', conceptId }, only: 'claude' },
    ]);
    expect(outcome).toMatchObject({ kind: 'script', stage: 'hooks', engine: 'claude', notes: [] });
    expect(outcome.view.script?.hooks.map((hook) => [hook.way, hook.model])).toEqual([
      ['scene first', A],
      ['a question', null],
      ['a number', null],
    ]);
    expect(outcome.view.script?.beats).toBe(
      '1:00 | The bill | Who has been paying\n3:00 | The plant | Why it closed',
    );
    expect(outcome.view.script?.status).toBe('drafting');
  });

  test('hooks: a beat written at length is kept whole, and one far too long is shortened and reported', async () => {
    const long = `Something is told here at length. `.repeat(12).trim();
    const tooLong = `Something is told here at length. `.repeat(60).trim();
    answer = [
      'HOOK 1',
      'WAY: scene first',
      'MODEL: none',
      'TEXT: It never stopped.',
      'BEATS',
      `BEAT: 1:00 | The bill | ${long}`,
      `BEAT: 3:00 | The plant | ${tooLong}`,
      'BEAT: 5:00 | The end | How it closes.',
    ].join('\n');

    const outcome = await engine.runScriptStage('hooks', MINE, conceptId, 'claude', () => {});

    const beats = (outcome.view.script?.beats ?? '').split('\n');
    expect(beats).toHaveLength(3);
    expect(beats[0]).toBe(`1:00 | The bill | ${long}`);
    expect(beats[1]?.length).toBeLessThan(tooLong.length);
    expect(beats[1]?.endsWith('at length.')).toBe(true);
    expect(outcome.notes).toEqual([expect.stringMatching(/^Beat 2 \(“The plant”\) was longer/)]);
  });

  test('draft: waits for a chosen hook and beats, then stores the script from its first heading', async () => {
    expect(engine.stageProblem('draft', MINE, conceptId)).toMatch(/Choose a hook/);
    await engine.runScriptStage('hooks', MINE, conceptId, undefined, () => {});
    engine.saveScript(MINE, conceptId, { chosenHook: 'It never stopped.' });
    answer = DRAFT;

    const outcome = await engine.runScriptStage('draft', MINE, conceptId, undefined, () => {});

    expect(asked.at(-1)).toMatchObject({ analysis: 'script-draft' });
    expect(outcome.view.script?.draft.startsWith('## HOOK\n[B-ROLL: a press')).toBe(true);
    expect(outcome.view.script?.draft).toContain('[CHECK: that it still runs]');
  });

  test('tighten: waits for a draft, and never touches the draft itself', async () => {
    expect(engine.stageProblem('tighten', MINE, conceptId)).toMatch(/no draft/);
    engine.saveScript(MINE, conceptId, { draft: DRAFT });
    answer = '## HOOK\nIt never stopped [CHECK: that it still runs].';

    const outcome = await engine.runScriptStage('tighten', MINE, conceptId, undefined, () => {});

    expect(asked.at(-1)).toMatchObject({ analysis: 'script-tighten' });
    expect(outcome.view.script?.tightened).toBe(answer);
    expect(outcome.view.script?.draft).toBe(DRAFT);
  });

  test('changes nothing when an answer holds no hook, or no script', async () => {
    answer = 'I could not reach the tools.';

    await expect(
      engine.runScriptStage('hooks', MINE, conceptId, undefined, () => {}),
    ).rejects.toThrow(/Nothing was changed/);
    engine.saveScript(MINE, conceptId, { draft: DRAFT });
    answer = '## HOOK\n[B-ROLL: only a cue]';
    await expect(
      engine.runScriptStage('tighten', MINE, conceptId, undefined, () => {}),
    ).rejects.toThrow(/not with a script/);
    expect(engine.findScriptView(MINE, conceptId)?.script).toMatchObject({
      hooks: [],
      tightened: '',
    });
  });

  test('is refused for a concept with no script, before anything is asked', async () => {
    await expect(
      engine.runScriptStage('hooks', OTHER, conceptId, undefined, () => {}),
    ).rejects.toThrow(/not one of this channel/);
    expect(asked).toEqual([]);
  });
});

