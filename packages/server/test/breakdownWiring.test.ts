const status = (id: EngineStatus['id'], installed: boolean): EngineStatus => ({
  id,
  label: id,
  installed,
  signedIn: null,
  version: null,
  ready: installed,
  note: null,
});

let folder: string;
let dbPath: string;
let downloads: string;
let engine: RunningEngine;

/** A stand-in for core's downloader: it writes a small whole MP4 where the real one would. */
function writesCopy(asked: string[] = []) {
  return async (videoId: string): Promise<FetchedVideo> => {
    asked.push(videoId);
    const temp = join(downloads, 'video-temp');
    mkdirSync(temp, { recursive: true });
    const path = join(temp, `${videoId}.mp4`);
    writeFileSync(path, tinyMp4());
    return { ok: true, path, bytes: 50, durationSeconds: 60, format: '360p mp4', via: 'yt-dlp' };
  };
}

function start(options: EngineOptions = {}, agy = true): RunningEngine {
  engine = createEngine(
    { dbPath, region: 'US', downloadsPath: downloads },
    {
      now: () => NOW,
      createSource: async () => source,
      storePath: dbPath,
      programEnv: { PATH: '' },
      fetchImage: async () => new Response(JPEG, { headers: { 'content-type': 'image/jpeg' } }),
      checkEngines: async () => [status('agy', agy), status('claude', true)],
      ...options,
    },
  );
  return engine;
}

const copiesLeft = (): readonly string[] =>
  existsSync(join(downloads, 'video-temp')) ? readdirSync(join(downloads, 'video-temp')) : [];

beforeEach(() => {
  folder = mkdtempSync(join(tmpdir(), 'jgtube-wiring-'));
  dbPath = join(folder, 'store.db');
  downloads = join(folder, 'downloads');
});

afterEach(async () => {
  await engine.shutdown();
  rmSync(folder, { recursive: true, force: true });
});

describe('watching a video through the engine', () => {
  const agySays = (response: string) => ({
    stdout: JSON.stringify({ status: 'SUCCESS', response }),
  });

  test('downloads a copy for Antigravity and removes it once the video has been watched', async () => {
    const asked: string[] = [];
    const { started, deps } = scripted(() => agySays('A whoosh on each cut.'));
    start({ spawn: deps.spawn, fetchVideoFile: writesCopy(asked) });

    const answer = await engine.watchVideo(DASHED, 'Describe the sound.');

    expect(answer).toMatchObject({ text: 'A whoosh on each cut.', engine: 'agy' });
    expect(asked).toEqual([DASHED]);
    // The id never reached the program's command line: it watched its own copy.
    expect(started[0]?.args.some((arg) => arg.includes(DASHED))).toBe(false);
    expect(copiesLeft()).toEqual([]);
  });

  test('removes the copy when the watch fails', async () => {
    const { deps } = scripted(() => ({ stderr: 'authentication required', code: 1 }));
    start({ spawn: deps.spawn, fetchVideoFile: writesCopy() });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      reason: 'not-signed-in',
    });
    expect(copiesLeft()).toEqual([]);
  });

  test('removes the copy when Jgtube is closed while the video is being watched', async () => {
    const hung = new FakeChild();
    start({ spawn: () => hung, fetchVideoFile: writesCopy(), closeGraceMs: 20 });
    const watching = engine.watchVideo(DASHED, 'Describe the sound.').catch(() => 'stopped');
    while (copiesLeft().length === 0) await settle();

    await engine.shutdown();

    expect(copiesLeft()).toEqual([]);
    hung.finish(undefined, 1);
    expect(await watching).toBe('stopped');
  });

  test('gives the downloader’s plain reason when no copy could be had', async () => {
    start({
      fetchVideoFile: async () => ({
        ok: false,
        kind: 'refused',
        message: 'YouTube refused this computer’s connection for now.',
        via: 'yt-dlp',
      }),
    });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining(
        'Antigravity had no copy of the video to watch: YouTube refused this computer’s connection for now.',
      ),
    });
  });

  test('gives the built-in download this engine’s own connection to YouTube', async () => {
    const asked: string[] = [];
    start({
      createSource: async () => ({
        ...source,
        fetchPlayer: async (videoId: string) => {
          asked.push(videoId);
          return { playability_status: { status: 'ERROR', reason: 'This video is private' } };
        },
      }),
    });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining('YouTube will not give this video: This video is private'),
    });
    expect(asked).toEqual([DASHED]);
  });

  test('says the connection cannot fetch a file when it is one that cannot', async () => {
    start();

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining('This connection to YouTube cannot fetch a video file'),
    });
  });
});

describe('a breakdown through the engine', () => {
  /** Stand-in engines: a frame study or the breakdown, told apart by the tools they are given. */
  function standInEngines() {
    const requests: Array<[EngineId, EngineRunRequest]> = [];
    const runEngine: EngineOptions['runEngine'] = async (id, request) => {
      requests.push([id, request]);
      const studies = request.allowedTools.length === 1;
      return { text: studies ? 'SECRET FRAME NOTES' : 'THE BREAKDOWN', turns: 5 };
    };
    return { requests, runEngine };
  }

  test('reads the channel, studies the best three by preview frames and writes, with no watcher', async () => {
    const { requests, runEngine } = standInEngines();
    const steps: BreakdownProgress[] = [];
    start({ runEngine }, false);

    const outcome = await engine.breakDown('@channelw', (step) => steps.push(step));

    expect(outcome).toMatchObject({
      channel: { id: CHANNEL, title: 'Channel W' },
      storedVideos: 6,
      text: 'THE BREAKDOWN',
      engine: 'claude',
      ownVideosFolder: join(downloads, 'my-videos'),
      supply: [],
    });
    expect(outcome.top.map((entry) => entry.captions)).toEqual(Array(5).fill('read'));
    expect(outcome.deep.map((entry) => [entry.videoId, entry.watch.done, entry.frames])).toEqual(
      [1, 2, 3].map((n) => [
        vid(n),
        false,
        { done: true, by: 'claude', kept: false, source: 'preview', available: 60 },
      ]),
    );
    expect(requests.map(([, request]) => request.allowedTools.length)).toEqual([1, 1, 1, 7]);
    expect(steps.at(-1)?.text).toBe('Writing the breakdown');
  });

  test('never puts what an engine wrote about a video into a later question', async () => {
    const { requests, runEngine } = standInEngines();
    start({ runEngine }, false);
    await engine.breakDown(CHANNEL, () => {});

    await engine.breakDown(CHANNEL, () => {});

    expect(engine.findVideoStudy(vid(1), 'frames')?.text).toBe('SECRET FRAME NOTES');
    expect(requests.every(([, request]) => !request.prompt.includes('SECRET'))).toBe(true);
    expect(requests.every(([, request]) => !request.systemPrompt.includes('SECRET'))).toBe(true);
    // The second press reused the three stored studies: only the writing ran again.
    expect(requests.map(([, request]) => request.allowedTools.length)).toEqual([1, 1, 1, 7, 7]);
  });

  test('names the chosen videos to the writing engine by id only, never by title', async () => {
    const { requests, runEngine } = standInEngines();
    start({ runEngine }, false);

    await engine.breakDown(CHANNEL, () => {});

    const writing = requests.at(-1)?.[1].prompt ?? '';
    expect(writing).toContain([1, 2, 3, 4, 5].map(vid).join(', '));
    expect(writing).not.toContain('Video 1');
    expect(requests[0]?.[1].prompt).toContain(`For the video ${vid(1)}:`);
  });

  test('is refused once Jgtube has begun closing', async () => {
    start({ runEngine: standInEngines().runEngine }, false);
    await engine.shutdown();

    await expect(engine.breakDown(CHANNEL, () => {})).rejects.toThrow(/closing/);
  });
});

describe('the engine’s readers a breakdown rests on', () => {
  test('serves frames cut from a video’s file when there are some, and preview frames otherwise', async () => {
    start();
    const cut = join(downloads, 'video-temp', `frames-${vid(1)}`);
    mkdirSync(cut, { recursive: true });
    writeFileSync(join(cut, 'sheet-001.jpg'), JPEG);
    writeFileSync(
      join(cut, 'index.json'),
      JSON.stringify({
        videoId: vid(1),
        cutAt: NOW.toISOString(),
        everySeconds: 1,
        columns: 5,
        rows: 5,
        frameWidth: 288,
        frameHeight: 162,
        frameCount: 12,
        sheets: [{ index: 0, file: 'sheet-001.jpg', frames: 12, firstSecond: 0, lastSecond: 11 }],
      }),
    );

    const fromFile = await engine.readVideoFrames(vid(1), 4, 0);
    const fromPreview = await engine.readVideoFrames(vid(2), 2, 1);

    expect(fromFile).toMatchObject({ source: 'file', frameCount: 12, sheetCount: 1 });
    expect(fromPreview).toMatchObject({ source: 'preview', frameCount: 60, sheetCount: 3 });
    expect(fromPreview?.sheets.map((entry) => entry.sheet.index)).toEqual([1, 2]);
  });

  test('saves the transcripts of a stored channel’s winners as files, and nothing for an unknown one', async () => {
    start();
    await engine.readChannelBrand(CHANNEL);

    const saved = await engine.saveTranscripts(CHANNEL);

    expect(saved?.folder).toBe(join(downloads, 'transcripts', 'Channel W'));
    expect(saved?.saved.map((entry) => entry.videoId)).toEqual([vid(1), vid(2), vid(3)]);
    expect(readFileSync(join(saved?.folder ?? '', `${vid(1)}.txt`), 'utf8')).toContain('hello');
    expect(await engine.saveTranscripts(`UC${'z'.repeat(22)}`)).toBeNull();
  });

  test('has no study of a video until one is stored, and says where the owner’s files go', () => {
    start();

    expect(engine.findVideoStudy(vid(1), 'watch')).toBeNull();
    expect(engine.ownVideosFolder()).toBe(join(downloads, 'my-videos'));
  });
});
