const NOW = new Date('2026-11-20T12:00:00Z');
const DAY_MS = 86_400_000;
const CHANNEL = `UC${'W'.repeat(22)}`;
const DASHED = '-aaaaaaaaaa';
const vid = (n: number) => `WWWWWWWWW${String(n).padStart(2, '0')}`;
const JPEG = new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 1, 2, 3, 4]);
const settle = () => new Promise((resolve) => setTimeout(resolve, 5));

const snapshot = (): ChannelSnapshot => ({
  channel: {
    id: CHANNEL,
    title: 'Channel W',
    handle: 'channelw',
    subscribers: 4000,
    subscribersHidden: false,
    videoCount: 6,
  },
  brand: { description: 'We explain things.', avatar: [], banner: [], keywords: [], links: [] },
  videos: [90_000, 40_000, 20_000, 1000, 1000, 1000].map((views, n) => ({
    id: vid(n + 1),
    channelId: CHANNEL,
    title: `Video ${n + 1}`,
    views,
    durationSeconds: 600,
    published: {
      date: new Date(NOW.getTime() - (10 + n) * DAY_MS),
      precision: 'day' as const,
      raw: 'x',
    },
  })),
});

const page = (videoId: string): VideoPage => ({
  videoId,
  details: { title: 'A video', description: 'About it', tags: [], durationSeconds: 600 },
  storyboard: [
    {
      templateUrl: `https://i.ytimg.com/sb/${videoId}/storyboard3_L2/M$M.jpg?sqp=x&sigh=y`,
      frameWidth: 160,
      frameHeight: 90,
      frameCount: 60,
      columns: 5,
      rows: 5,
      intervalMs: 10_000,
      sheetCount: 3,
    },
  ],
  transcript: { language: 'en', autoGenerated: true, segments: [{ startMs: 0, text: 'hello' }] },
});

const source: YouTubeSource = {
  resolveChannelId: async () => CHANNEL,
  getSidebar: async () => [],
  fetchChannel: async () => snapshot(),
  fetchVideoPage: async (videoId) => page(videoId),
};

const status = (id: EngineStatus['id'], installed: boolean): EngineStatus => ({
  id,
  label: id,
  installed,
  signedIn: null,
  version: null,
  ready: installed,
  note: null,
});

let folder: string;
let dbPath: string;
let downloads: string;
let engine: RunningEngine;

/** A stand-in for core's downloader: it writes a small whole MP4 where the real one would. */
function writesCopy(asked: string[] = []) {
  return async (videoId: string): Promise<FetchedVideo> => {
    asked.push(videoId);
    const temp = join(downloads, 'video-temp');
    mkdirSync(temp, { recursive: true });
    const path = join(temp, `${videoId}.mp4`);
    writeFileSync(path, tinyMp4());
    return { ok: true, path, bytes: 50, durationSeconds: 60, format: '360p mp4', via: 'yt-dlp' };
  };
}

function start(options: EngineOptions = {}, agy = true): RunningEngine {
  engine = createEngine(
    { dbPath, region: 'US', downloadsPath: downloads },
    {
      now: () => NOW,
      createSource: async () => source,
      storePath: dbPath,
      programEnv: { PATH: '' },
      fetchImage: async () => new Response(JPEG, { headers: { 'content-type': 'image/jpeg' } }),
      checkEngines: async () => [status('agy', agy), status('claude', true)],
      ...options,
    },
  );
  return engine;
}

const copiesLeft = (): readonly string[] =>
  existsSync(join(downloads, 'video-temp')) ? readdirSync(join(downloads, 'video-temp')) : [];

beforeEach(() => {
  folder = mkdtempSync(join(tmpdir(), 'jgtube-wiring-'));
  dbPath = join(folder, 'store.db');
  downloads = join(folder, 'downloads');
});

afterEach(async () => {
  await engine.shutdown();
  rmSync(folder, { recursive: true, force: true });
});

describe('watching a video through the engine', () => {
  const agySays = (response: string) => ({
    stdout: JSON.stringify({ status: 'SUCCESS', response }),
  });

  test('downloads a copy for Antigravity and removes it once the video has been watched', async () => {
    const asked: string[] = [];
    const { started, deps } = scripted(() => agySays('A whoosh on each cut.'));
    start({ spawn: deps.spawn, fetchVideoFile: writesCopy(asked) });

    const answer = await engine.watchVideo(DASHED, 'Describe the sound.');

    expect(answer).toMatchObject({ text: 'A whoosh on each cut.', engine: 'agy' });
    expect(asked).toEqual([DASHED]);
    // The id never reached the program's command line: it watched its own copy.
    expect(started[0]?.args.some((arg) => arg.includes(DASHED))).toBe(false);
    expect(copiesLeft()).toEqual([]);
  });

  test('removes the copy when the watch fails', async () => {
    const { deps } = scripted(() => ({ stderr: 'authentication required', code: 1 }));
    start({ spawn: deps.spawn, fetchVideoFile: writesCopy() });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      reason: 'not-signed-in',
    });
    expect(copiesLeft()).toEqual([]);
  });

  test('removes the copy when Jgtube is closed while the video is being watched', async () => {
    const hung = new FakeChild();
    start({ spawn: () => hung, fetchVideoFile: writesCopy(), closeGraceMs: 20 });
    const watching = engine.watchVideo(DASHED, 'Describe the sound.').catch(() => 'stopped');
    while (copiesLeft().length === 0) await settle();

    await engine.shutdown();

    expect(copiesLeft()).toEqual([]);
    hung.finish(undefined, 1);
    expect(await watching).toBe('stopped');
  });

  test('gives the downloader’s plain reason when no copy could be had', async () => {
    start({
      fetchVideoFile: async () => ({
        ok: false,
        kind: 'refused',
        message: 'YouTube refused this computer’s connection for now.',
        via: 'yt-dlp',
      }),
    });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining(
        'Antigravity had no copy of the video to watch: YouTube refused this computer’s connection for now.',
      ),
    });
  });

  test('gives the built-in download this engine’s own connection to YouTube', async () => {
    const asked: string[] = [];
    start({
      createSource: async () => ({
        ...source,
        fetchPlayer: async (videoId: string) => {
          asked.push(videoId);
          return { playability_status: { status: 'ERROR', reason: 'This video is private' } };
        },
      }),
    });

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining('YouTube will not give this video: This video is private'),
    });
    expect(asked).toEqual([DASHED]);
  });

  test('says the connection cannot fetch a file when it is one that cannot', async () => {
    start();

    await expect(engine.watchVideo(DASHED, 'Describe the sound.')).rejects.toMatchObject({
      message: expect.stringContaining('This connection to YouTube cannot fetch a video file'),
    });
  });
});

describe('a breakdown through the engine', () => {
  const FRAME_TOOLS = ['mcp__jgtube__view_video_frames'];
  const thumb = markerLines('THUMBNAIL PROMPT');
  const master = markerLines('MASTER PROMPT');
  /** What a stand-in engine writes for a part, told from the number in its question. */
  const partText = (prompt: string): string => {
    const number = /This is part (\d) of 7/.exec(prompt)?.[1] ?? '?';
    if (number === '2') {
      return `SECRET PART 2\n${thumb.start}\nSECRET PICTURE OF [SUBJECT]\n${thumb.end}`;
    }
    if (number === '7') {
      return `SECRET PART 7\n${master.start}\nSECRET SCRIPT RULES [CHECK: ...]\n${master.end}`;
    }
    return `SECRET PART ${number}`;
  };

  /** Stand-in engines: a frame study or a part of the breakdown, told apart by the tools they are given. */
  function standInEngines() {
    const requests: Array<[EngineId, EngineRunRequest]> = [];
    const runEngine: EngineOptions['runEngine'] = async (id, request) => {
      requests.push([id, request]);
      const studies = request.allowedTools.join() === FRAME_TOOLS.join();
      return { text: studies ? 'SECRET FRAME NOTES' : partText(request.prompt), turns: 5 };
    };
    const partRuns = (): readonly string[] =>
      requests.flatMap(([, request]) => /This is part \d of 7/.exec(request.prompt) ?? []);
    return { requests, runEngine, partRuns };
  }
  const ALL_PARTS = [1, 2, 3, 4, 5, 6, 7].map((n) => `This is part ${n} of 7`);

  test('reads the channel, studies the best three by preview frames and writes the seven parts, with no watcher', async () => {
    const { requests, runEngine, partRuns } = standInEngines();
    const steps: BreakdownProgress[] = [];
    start({ runEngine }, false);

    const outcome = await engine.breakDown('@channelw', (step) => steps.push(step));

    expect(outcome).toMatchObject({
      channel: { id: CHANNEL, title: 'Channel W' },
      storedVideos: 6,
      titles: 6,
      notSaved: null,
      ownVideosFolder: join(downloads, 'my-videos'),
      supply: [],
    });
    expect(outcome.top.map((entry) => entry.captions)).toEqual(Array(5).fill('read'));
    expect(outcome.deep.map((entry) => [entry.videoId, entry.watch.done, entry.frames])).toEqual(
      [1, 2, 3].map((n) => [
        vid(n),
        false,
        { done: true, by: 'claude', kept: false, source: 'preview', available: 60 },
      ]),
    );
    expect(requests.slice(0, 3).map(([, request]) => request.allowedTools)).toEqual([
      FRAME_TOOLS,
      FRAME_TOOLS,
      FRAME_TOOLS,
    ]);
    expect(partRuns()).toEqual(ALL_PARTS);
    expect(outcome.parts.map((part) => [part.part, part.outcome])).toEqual(
      ['titles', 'thumbnails', 'scripts', 'picture', 'strategy', 'plan', 'master'].map((part) => [
        part,
        'written',
      ]),
    );
    expect(steps.at(-1)?.text).toBe('Saving the breakdown as text files');
  });

  test('offers each part only its own tools, through a connector started for that run', async () => {
    const { requests, runEngine } = standInEngines();
    start({ runEngine }, false);

    await engine.breakDown(CHANNEL, () => {});

    const tools = requests
      .slice(3)
      .map(([, request]) => request.mcpServers['jgtube']?.env?.['JGTUBE_TOOLS']);
    expect(tools).toEqual([
      'get_channel_videos,get_video_details',
      'get_channel_brand,get_channel_videos,view_thumbnails',
      'get_transcript,get_transcript_pace,get_channel_videos',
      'get_frame_study,get_video_watch,get_channel_videos',
      'get_breakdown_part,get_channel_videos',
      'get_breakdown_part,get_transcript_pace,get_frame_study,get_video_watch',
      'get_breakdown_part',
    ]);
  });

  test('saves the breakdown as four text files in a folder named after the channel, and opens it again', async () => {
    const { runEngine } = standInEngines();
    start({ runEngine }, false);

    const outcome = await engine.breakDown(CHANNEL, () => {});

    const folder = join(downloads, 'breakdowns', 'Channel W');
    expect(outcome.breakdown.folder).toBe(folder);
    expect(readdirSync(folder).sort()).toEqual([
      'breakdown.txt',
      'index.json',
      'master-prompt.txt',
      'production-plan.txt',
      'thumbnail-prompt.txt',
    ]);
    expect(readFileSync(join(folder, 'master-prompt.txt'), 'utf8')).toBe(
      'SECRET SCRIPT RULES [CHECK: ...]\n',
    );
    expect(readFileSync(join(folder, 'thumbnail-prompt.txt'), 'utf8')).toBe(
      'SECRET PICTURE OF [SUBJECT]\n',
    );
    expect(readFileSync(join(folder, 'production-plan.txt'), 'utf8')).toBe('SECRET PART 6\n');
    expect(JSON.parse(readFileSync(join(folder, 'index.json'), 'utf8'))).toMatchObject({
      channelId: CHANNEL,
    });
    // The stored breakdown is read back without an engine, by handle or by id.
    const again = await engine.findBreakdown('@channelw');
    expect(again).toEqual(outcome.breakdown);
    expect(again?.parts.find((part) => part.id === 'master')).toMatchObject({
      state: 'written',
      body: 'SECRET PART 7',
      prompt: 'SECRET SCRIPT RULES [CHECK: ...]',
      engine: 'claude',
    });
    expect(again?.files.map((file) => [file.name, file.available])).toEqual([
      ['breakdown.txt', true],
      ['production-plan.txt', true],
      ['thumbnail-prompt.txt', true],
      ['master-prompt.txt', true],
      // The stand-in picture part sets out no style lock.
      ['style-lock.txt', false],
    ]);
    expect(engine.breakdownText(CHANNEL, 'thumbnail')).toMatchObject({
      channel: { id: CHANNEL, title: 'Channel W' },
      file: { name: 'thumbnail-prompt.txt', text: 'SECRET PICTURE OF [SUBJECT]\n' },
    });
  });

  test('has no stored breakdown for a channel that was never broken down, or never read', async () => {
    start({ runEngine: standInEngines().runEngine }, false);
    await engine.readChannelBrand(CHANNEL);

    expect(await engine.findBreakdown(CHANNEL)).toBeNull();
    expect(await engine.findBreakdown(`UC${'x'.repeat(22)}`)).toBeNull();
    expect(engine.breakdownText(`UC${'x'.repeat(22)}`, 'whole')).toBeNull();
    expect(engine.breakdownText(CHANNEL, 'whole')?.file).toMatchObject({
      text: null,
      reason: 'No part of the breakdown has been written.',
    });
  });

  test('never puts what an engine wrote, about a video or as a part, into any question', async () => {
    const { requests, runEngine, partRuns } = standInEngines();
    start({ runEngine }, false);
    await engine.breakDown(CHANNEL, () => {});
    // A second press with nothing changed starts no engine at all.
    await engine.breakDown(CHANNEL, () => {});
    expect(requests).toHaveLength(10);
    // Starting from nothing studies and writes everything again, with every part already stored.
    await engine.breakDown(CHANNEL, () => {}, { fresh: true });

    expect(partRuns()).toEqual([...ALL_PARTS, ...ALL_PARTS]);
    expect(engine.findVideoStudy(vid(1), 'frames')?.text).toBe('SECRET FRAME NOTES');
    const stored = [
      'basis',
      'titles',
      'thumbnails',
      'scripts',
      'picture',
      'strategy',
      'plan',
      'master',
    ].map((part) => engine.findBreakdownPart(CHANNEL, part as never));
    expect(stored.every((part) => part?.written === true)).toBe(true);
    const said = requests.flatMap(([, request]) => [request.prompt, request.systemPrompt]);
    for (const text of said) {
      expect(text).not.toContain('SECRET');
      for (const part of stored) {
        expect(text).not.toContain(part?.written ? part.text : 'never');
      }
      // Titles are what a stranger wrote; they reach an engine as tool results only.
      expect(text).not.toContain('Video 1');
      expect(text).not.toContain('Channel W');
    }
  });

  test('names the chosen videos to each part by id only, never by title', async () => {
    const { requests, runEngine } = standInEngines();
    start({ runEngine }, false);

    await engine.breakDown(CHANNEL, () => {});

    const titles = requests[3]?.[1].prompt ?? '';
    expect(titles).toContain('This is part 1 of 7');
    // Six stored videos, most viewed first; the last three share their views and go by id.
    expect(titles).toContain([1, 2, 3, 4, 5, 6].map(vid).join(', '));
    expect(titles).toContain('6 titles to study, most viewed first, out of 6 stored');
    expect(requests[5]?.[1].prompt).toContain([1, 2, 3].map(vid).join(', '));
    expect(requests[0]?.[1].prompt).toContain(`For the video ${vid(1)}:`);
  });

  test('lets the one engine the owner chose write every part it can, and says which it cannot', async () => {
    const { requests, runEngine } = standInEngines();
    start({ runEngine }, true);

    const outcome = await engine.breakDown(CHANNEL, () => {}, { only: 'agy' });

    expect(requests.every(([id]) => id === 'agy')).toBe(true);
    expect(outcome.parts.map((part) => part.outcome)).toEqual([
      'written',
      'failed',
      'written',
      'written',
      'written',
      'written',
      'written',
    ]);
    expect(outcome.parts[1]).toMatchObject({
      reason:
        'The breakdown’s part on thumbnails cannot be done by Antigravity CLI: it needs Claude Code or Codex CLI. Choose one of those, or Automatic.',
    });
    expect(outcome.breakdown.files.find((file) => file.id === 'thumbnail')).toEqual({
      id: 'thumbnail',
      name: 'thumbnail-prompt.txt',
      available: false,
      reason:
        'The thumbnails part was not written: The breakdown’s part on thumbnails cannot be done by Antigravity CLI: it needs Claude Code or Codex CLI. Choose one of those, or Automatic.',
    });
  });

  test('reads a video’s stored length, for the numbers worked out from a frame study', async () => {
    start({ runEngine: standInEngines().runEngine }, false);
    await engine.readChannelBrand(CHANNEL);

    expect(engine.findVideoSeconds(vid(1))).toBe(600);
    expect(engine.findVideoSeconds('nostoredvid')).toBeNull();
  });

  test('is refused once Jgtube has begun closing', async () => {
    start({ runEngine: standInEngines().runEngine }, false);
    await engine.shutdown();

    await expect(engine.breakDown(CHANNEL, () => {})).rejects.toThrow(/closing/);
  });
});

describe('the engine’s readers a breakdown rests on', () => {
  test('serves frames cut from a video’s file when there are some, and preview frames otherwise', async () => {
    start();
    const cut = join(downloads, 'video-temp', `frames-${vid(1)}`);
    mkdirSync(cut, { recursive: true });
    writeFileSync(join(cut, 'sheet-001.jpg'), JPEG);
    writeFileSync(
      join(cut, 'index.json'),
      JSON.stringify({
        videoId: vid(1),
        cutAt: NOW.toISOString(),
        everySeconds: 1,
        columns: 5,
        rows: 5,
        frameWidth: 288,
        frameHeight: 162,
        frameCount: 12,
        sheets: [{ index: 0, file: 'sheet-001.jpg', frames: 12, firstSecond: 0, lastSecond: 11 }],
      }),
    );

    const fromFile = await engine.readVideoFrames(vid(1), 4, 0);
    const fromPreview = await engine.readVideoFrames(vid(2), 2, 1);

    expect(fromFile).toMatchObject({ source: 'file', frameCount: 12, sheetCount: 1 });
    expect(fromPreview).toMatchObject({ source: 'preview', frameCount: 60, sheetCount: 3 });
    expect(fromPreview?.sheets.map((entry) => entry.sheet.index)).toEqual([1, 2]);
  });

  test('saves the transcripts of a stored channel’s winners as files, and nothing for an unknown one', async () => {
    start();
    await engine.readChannelBrand(CHANNEL);

    const saved = await engine.saveTranscripts(CHANNEL);

    expect(saved?.folder).toBe(join(downloads, 'transcripts', 'Channel W'));
    expect(saved?.saved.map((entry) => entry.videoId)).toEqual([vid(1), vid(2), vid(3)]);
    expect(readFileSync(join(saved?.folder ?? '', `${vid(1)}.txt`), 'utf8')).toContain('hello');
    expect(await engine.saveTranscripts(`UC${'z'.repeat(22)}`)).toBeNull();
  });

  test('has no study of a video until one is stored, and says where the owner’s files go', () => {
    start();

    expect(engine.findVideoStudy(vid(1), 'watch')).toBeNull();
    expect(engine.ownVideosFolder()).toBe(join(downloads, 'my-videos'));
  });
});
