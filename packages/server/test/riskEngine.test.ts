import {
  SqliteChannelRepo,
  SqliteConceptRepo,
  SqliteEdgeRepo,
  SqliteMapRepo,
  SqliteRiskRepo,
  SqliteScriptRepo,
  SqliteVideoPageRepo,
  SqliteVideoRepo,
  freezeMapSnapshot,
  openDatabase,
} from '@jgtube/core';
import { beforeEach, describe, expect, test } from 'vitest';
import { riskEngine } from '../src/riskEngine';
import type { RiskEngine } from '../src/riskTypes';

type StorableVideo = Parameters<SqliteVideoRepo['upsertMany']>[0][number];

const NOW = new Date('2026-11-21T12:00:00Z');
const LATER = new Date('2026-11-21T13:00:00Z');
const CENTER = `UC${'c'.repeat(22)}`;
const PEER = `UC${'p'.repeat(22)}`;
const NO_MAP = `UC${'n'.repeat(22)}`;

let clock: Date;
let engine: RiskEngine;
let scripts: SqliteScriptRepo;
let conceptId: number;
let asked: unknown[];
let answerText: string;

const video = (channelId: string, id: string, days: number): StorableVideo => ({
  id: id.padEnd(11, '_'),
  channelId,
  title: `Title of ${id}`,
  views: 1000,
  durationSeconds: 600,
  published: { date: new Date(NOW.getTime() - days * 86_400_000), precision: 'day', raw: '' },
});

beforeEach(() => {
  const db = openDatabase(':memory:');
  scripts = new SqliteScriptRepo(db);
  const repos = {
    channels: new SqliteChannelRepo(db),
    videos: new SqliteVideoRepo(db),
    edges: new SqliteEdgeRepo(db),
    maps: new SqliteMapRepo(db),
    concepts: new SqliteConceptRepo(db),
    scripts,
    transcripts: new SqliteVideoPageRepo(db),
    risks: new SqliteRiskRepo(db),
  };
  for (const id of [CENTER, PEER]) {
    repos.channels.upsert(
      {
        id,
        title: id,
        handle: null,
        subscribers: 1000,
        subscribersHidden: false,
        videoCount: null,
      },
      NOW,
    );
    repos.videos.upsertMany(
      [1, 2, 3, 4, 5].map((n) => video(id, `${id.slice(2, 3)}vid${n}`, 10 + n)),
      NOW,
    );
  }
  repos.maps.create(
    {
      centerChannelId: CENTER,
      depth: 1,
      region: 'US',
      members: [
        { channelId: CENTER, steps: 0 },
        { channelId: PEER, steps: 1 },
      ],
    },
    NOW,
  );
  freezeMapSnapshot(repos, CENTER, NOW);
  repos.transcripts.save(
    'pvid1______',
    {
      language: 'en',
      autoGenerated: false,
      segments: [
        { startMs: 0, text: 'the army quietly built a city under the ice and then walked away' },
      ],
    },
    NOW,
  );
  const batch = repos.concepts.createBatch(
    {
      centerChannelId: CENTER,
      inspiration: [],
      hookModels: [],
      format: null,
      angle: null,
      length: 'long',
    },
    NOW,
  );
  const [stored] = repos.concepts.addConcepts(
    batch,
    [
      {
        title: 'The Secret City Under the Ice',
        altTitles: ['A', 'B'],
        thumbnail: 'A city in a glacier',
        overlay: 'STILL THERE?',
        hook: 'h',
        hookStyle: null,
        restsOn: 'r',
        needs: 'nothing',
        origin: 'batch',
        parentId: null,
        engine: 'test',
      },
    ],
    NOW,
  );
  conceptId = stored?.id ?? 0;
  repos.concepts.setKept(CENTER, conceptId, true);
  scripts.save(
    CENTER,
    conceptId,
    {
      draft: 'In 1959 the army quietly built a city under the ice and then left. [CHECK: the year]',
    },
    NOW,
  );
  clock = NOW;
  asked = [];
  answerText = '';
  engine = riskEngine({
    now: () => clock,
    repos,
    analyse: async (...args) => {
      asked.push(args);
      return { text: answerText, turns: 1, engine: 'claude', skipped: [] };
    },
  });
});

describe('riskEngine', () => {
  test('lists the scripted concepts and what code finds for the chosen one', () => {
    const view = engine.findRisk(CENTER, conceptId);

    expect(view?.concepts).toEqual([{ conceptId, title: 'The Secret City Under the Ice' }]);
    expect(view?.check).toMatchObject({
      conceptId,
      stage: 'draft',
      transcriptsCompared: 1,
      unchecked: [{ what: 'the year' }],
      ai: null,
    });
    expect(view?.check?.overlaps.map((overlap) => overlap.id)).toEqual(['o1']);
    expect(engine.findRisk(CENTER, null)?.check).toBeNull();
    expect(engine.findRisk(NO_MAP, conceptId)).toBeNull();
  });

  test('asks one question and keeps only claims and notes that check out', async () => {
    answerText = [
      'CLAIM',
      'WHERE: title',
      'SAYS: Secret City',
      'SCRIPT: the army quietly built a city',
      'WHY: The script does not say it was secret.',
      '',
      'CLAIM',
      'WHERE: overlay',
      'SAYS: Words not on the overlay',
      'SCRIPT: NONE',
      'WHY: Invented.',
      '',
      'OVERLAP',
      'ID: o1',
      'NOTE: Shares a competitor’s sentence about the camp.',
    ].join('\n');

    const outcome = await engine.askRisk(CENTER, conceptId);

    expect(asked).toEqual([['risk-check', CENTER, undefined, { kind: 'risk', conceptId }]]);
    expect(outcome).toEqual({ claims: 1, notes: 1, dropped: 1, engine: 'claude' });
    expect(engine.findRisk(CENTER, conceptId)?.check?.ai).toMatchObject({
      claims: [{ where: 'title', says: 'Secret City' }],
      notes: [{ id: 'o1' }],
      engine: 'claude',
      scriptChangedSince: false,
    });
  });

  test('says when the script changed after the last check', async () => {
    answerText = 'NOTHING TO LIST';
    await engine.askRisk(CENTER, conceptId);
    clock = LATER;
    scripts.save(CENTER, conceptId, { draft: 'A new draft.' }, LATER);

    expect(engine.findRisk(CENTER, conceptId)?.check?.ai?.scriptChangedSince).toBe(true);
  });

  test('refuses a concept without a script, and hands the tool what code found', async () => {
    await expect(engine.askRisk(CENTER, 999)).rejects.toThrow(/no kept concept/);
    expect(engine.riskFindings(CENTER, conceptId)).toMatchObject({
      stage: 'draft',
      transcriptsCompared: 1,
      overlaps: [{ id: 'o1', videoId: 'pvid1______' }],
      unchecked: [{ what: 'the year' }],
    });
    expect(engine.riskFindings(CENTER, 999)).toBeNull();
    expect(engine.riskFindings(NO_MAP, conceptId)).toBeNull();
  });
});
