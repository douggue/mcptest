import {
  SqliteVideoStudyRepo,
  openDatabase,
  type FrameSheetCut,
  type StoredVideo,
  type StudiedFrames,
} from '@jgtube/core';
import { beforeEach, describe, expect, test } from 'vitest';
import { breakDown, type BreakdownDeps, type BreakdownFiles } from '../src/breakdownEngine';
import type { BreakdownProgress } from '../src/breakdownTypes';
import { EngineRunError } from '../src/engines/failure';
import type { VideoDownload } from '../src/engines/videoWatch';

const NOW = new Date('2026-11-20T12:00:00Z');
const DAY_MS = 86_400_000;
const CHANNEL = `UC${'a'.repeat(22)}`;
const vid = (n: number) => `video${String(n).padStart(6, '0')}`;

const video = (n: number, views: number, durationSeconds: number | null = 600): StoredVideo => ({
  id: vid(n),
  channelId: CHANNEL,
  title: `Video ${n}`,
  views,
  durationSeconds,
  published: { date: new Date(NOW.getTime() - (10 + n) * DAY_MS), precision: 'day', raw: 'x' },
  fetchedAt: NOW,
});

/** Six stored videos: 1 is far above the rest, then 2, 3, 4, 5; 6 is ordinary. */
const VIDEOS = [
  video(1, 90_000),
  video(2, 40_000),
  video(3, 20_000),
  video(4, 9000),
  video(5, 5000),
  video(6, 1000),
  video(7, 1000),
  video(8, 1000),
];

/** What happened in one run, in order, as short words. */
let log: string[];
let steps: BreakdownProgress[];
let studies: SqliteVideoStudyRepo;

interface World {
  readonly videos?: readonly StoredVideo[];
  readonly own?: Readonly<Record<string, string>>;
  readonly ffmpeg?: boolean;
  readonly watchesFiles?: boolean;
  readonly fetch?: (videoId: string) => VideoDownload;
  readonly cut?: (videoId: string) => FrameSheetCut;
  readonly forWatching?: (videoId: string, path: string) => VideoDownload;
  readonly preview?: (videoId: string) => StudiedFrames | null;
  readonly watch?: (videoId: string) => string;
  readonly noCaptions?: readonly string[];
  readonly stop?: AbortController;
}

function world(setup: World = {}): BreakdownDeps {
  const cutNow = new Set<string>();
  const files: BreakdownFiles = {
    ownFolder: () => '/downloads/my-videos',
    own: async (videoId) => setup.own?.[videoId] ?? null,
    fetch: async (videoId) => {
      log.push(`fetch ${videoId}`);
      const copy = setup.fetch?.(videoId) ?? { ok: false, reason: 'YouTube refused' };
      return copy.ok
        ? { ...copy, remove: async () => void log.push(`remove copy ${videoId}`) }
        : copy;
    },
    canCut: async () => setup.ffmpeg ?? false,
    cut: async (videoId, path) => {
      log.push(`cut ${videoId} from ${path}`);
      const cut = setup.cut?.(videoId) ?? {
        ok: true,
        folder: '/f',
        sheetCount: 24,
        frameCount: 600,
      };
      if (cut.ok) cutNow.add(videoId);
      return cut;
    },
    removeFrames: async (videoId) => {
      cutNow.delete(videoId);
      log.push(`remove frames ${videoId}`);
    },
    forWatching: async (videoId, path) => setup.forWatching?.(videoId, path) ?? { ok: true, path },
  };
  return {
    now: () => NOW,
    stop: (setup.stop ?? new AbortController()).signal,
    studies,
    files,
    readChannel: async () => ({ id: CHANNEL, title: 'Some Bakery' }),
    listVideos: () => setup.videos ?? VIDEOS,
    readTranscript: async (videoId) => {
      if (videoId === vid(5)) throw new Error('YouTube did not answer');
      return {
        videoId,
        transcript: setup.noCaptions?.includes(videoId)
          ? null
          : { language: 'en', autoGenerated: true, segments: [{ startMs: 0, text: 'hello' }] },
        fetchedAt: NOW,
        fromStore: true,
      };
    },
    framesAvailable: async (videoId) =>
      cutNow.has(videoId)
        ? { source: 'file', available: 600 }
        : setup.preview
          ? setup.preview(videoId)
          : { source: 'preview', available: 120 },
    watchesFiles: async () => setup.watchesFiles ?? false,
    watchVideo: async (videoId, _question, options) => {
      const copy = await options?.download?.(videoId, new AbortController().signal);
      log.push(`watch ${videoId} ${copy?.ok ? `file ${copy.path}` : `no file: ${copy?.reason}`}`);
      if (!setup.watch) {
        throw new EngineRunError('not-installed', 'No engine on this computer can watch a video.');
      }
      options?.onStep?.({ kind: 'watching', engine: 'agy' });
      if (copy?.ok) await copy.remove?.();
      return { text: setup.watch(videoId), turns: null, engine: 'agy', skipped: [] };
    },
    studyFrames: async (videoId, only) => {
      log.push(`study frames ${videoId}${only ? ` only ${only}` : ''}`);
      if (videoId === vid(3)) throw new EngineRunError('timeout', 'Claude took too long.');
      return { text: `Frames of ${videoId}.`, turns: 9, engine: 'claude', skipped: [] };
    },
    write: async (channel, only, focus) => {
      log.push(`write ${channel} top ${focus.top.length} deep ${focus.deep.length}`);
      return { text: 'THE BREAKDOWN', turns: 20, engine: only ?? 'claude', skipped: [] };
    },
  };
}

const run = (deps: BreakdownDeps, choices = {}) =>
  breakDown(deps, '@somebakery', (progress) => steps.push(progress), choices);

beforeEach(() => {
  log = [];
  steps = [];
  studies = new SqliteVideoStudyRepo(openDatabase(':memory:'));
});

describe('a breakdown where nothing can watch and there is no ffmpeg', () => {
  test('studies the top five, the best three by YouTube’s preview frames, and still writes', async () => {
    const outcome = await run(world());

    expect(outcome).toMatchObject({
      channel: { id: CHANNEL, title: 'Some Bakery' },
      storedVideos: 8,
      text: 'THE BREAKDOWN',
      engine: 'claude',
      skipped: [],
      ownVideosFolder: '/downloads/my-videos',
    });
    expect(outcome.top.map((entry) => [entry.videoId, entry.captions])).toEqual([
      [vid(1), 'read'],
      [vid(2), 'read'],
      [vid(3), 'read'],
      [vid(4), 'read'],
      [vid(5), 'failed'],
    ]);
    expect(outcome.deep.map((entry) => entry.videoId)).toEqual([vid(1), vid(2), vid(3)]);
    expect(outcome.deep[0]).toEqual({
      videoId: vid(1),
      title: 'Video 1',
      file: {
        used: 'none',
        reason:
          'Neither ffmpeg nor Antigravity is installed, so a file of this video would not be used.',
      },
      watch: { done: false, reason: 'No engine on this computer can watch a video.' },
      frames: { done: true, by: 'claude', kept: false, source: 'preview', available: 120 },
    });
    // No download is attempted when nothing here would use the file.
    expect(log.filter((line) => line.startsWith('fetch'))).toEqual([]);
    expect(outcome.supply).toEqual([]);
    expect(log.at(-1)).toBe(`write ${CHANNEL} top 5 deep 3`);
  });

  test('records a frame study that failed with its reason, and carries on with the rest', async () => {
    const outcome = await run(world());

    expect(outcome.deep[2]?.frames).toEqual({ done: false, reason: 'Claude took too long.' });
    expect(outcome.deep[1]?.frames).toMatchObject({ done: true });
    expect(studies.find(vid(3), 'frames')).toBeNull();
  });

  test('stores each frame study with where its frames came from', async () => {
    await run(world());

    expect(studies.find(vid(1), 'frames')).toMatchObject({
      engine: 'claude',
      text: `Frames of ${vid(1)}.`,
      frames: { source: 'preview', available: 120 },
    });
  });

  test('says there are no frames to study for a video YouTube has no preview of', async () => {
    const outcome = await run(world({ preview: () => null }));

    expect(outcome.deep[0]?.frames).toEqual({
      done: false,
      reason:
        'YouTube has no preview frames for this video, and there was no video file to cut frames from.',
    });
  });

  test('names a top video that has no captions', async () => {
    const outcome = await run(world({ noCaptions: [vid(2)] }));

    expect(outcome.top[1]).toEqual({ videoId: vid(2), title: 'Video 2', captions: 'none' });
  });

  test('reports each step in plain words, naming the video', async () => {
    await run(world());

    expect(steps.map((step) => step.step)).toEqual([
      'reading',
      'frames',
      'frames',
      'frames',
      'writing',
    ]);
    expect(steps[1]?.text).toBe(
      'Video 1 of 3, “Video 1”: an AI is going through its 120 frames, YouTube’s own preview frames',
    );
    expect(steps.at(-1)?.text).toBe('Writing the breakdown');
  });
});

describe('a breakdown with ffmpeg and an engine that watches files', () => {
  const able: World = {
    ffmpeg: true,
    watchesFiles: true,
    fetch: (videoId) => ({ ok: true, path: `/temp/${videoId}.mp4` }),
    watch: (videoId) => `Sound of ${videoId}.`,
  };

  test('downloads each deep video once, uses it for the watch and the frames, then removes it', async () => {
    const outcome = await run(world(able));

    expect(log.filter((line) => line.includes(vid(1)))).toEqual([
      `fetch ${vid(1)}`,
      `watch ${vid(1)} file /temp/${vid(1)}.mp4`,
      `cut ${vid(1)} from /temp/${vid(1)}.mp4`,
      `study frames ${vid(1)}`,
      `remove frames ${vid(1)}`,
      `remove copy ${vid(1)}`,
    ]);
    expect(outcome.deep[0]).toMatchObject({
      file: { used: 'downloaded' },
      watch: { done: true, by: 'agy', kept: false },
      frames: { done: true, source: 'file', available: 600 },
    });
    expect(studies.find(vid(1), 'watch')?.text).toBe(`Sound of ${vid(1)}.`);
  });

  test('says which video it is on, and which engine is watching', async () => {
    await run(world(able));

    expect(steps.slice(1, 5).map((step) => step.text)).toEqual([
      'Video 1 of 3, “Video 1”: downloading the video',
      'Video 1 of 3, “Video 1”: Antigravity is watching it',
      'Video 1 of 3, “Video 1”: cutting one frame a second from the file',
      'Video 1 of 3, “Video 1”: an AI is going through its 600 frames, cut from the video file, one a second',
    ]);
  });

  test('uses the owner’s own file first, downloads nothing for it, and never removes it', async () => {
    const outcome = await run(world({ ...able, own: { [vid(1)]: '/mine/Video 1.mp4' } }));

    expect(log.filter((line) => line.includes(vid(1)))).toEqual([
      `watch ${vid(1)} file /mine/Video 1.mp4`,
      `cut ${vid(1)} from /mine/Video 1.mp4`,
      `study frames ${vid(1)}`,
      `remove frames ${vid(1)}`,
    ]);
    expect(outcome.deep[0]?.file).toEqual({ used: 'own' });
    expect(steps[1]?.text).toBe('Video 1 of 3, “Video 1”: using the file you gave');
  });

  test('lists a video that could not be downloaded as one the owner can supply, and falls back', async () => {
    const outcome = await run(
      world({ ...able, fetch: () => ({ ok: false, reason: 'YouTube refused this computer' }) }),
    );

    expect(outcome.supply).toEqual(
      [1, 2, 3].map((n) => ({
        videoId: vid(n),
        title: `Video ${n}`,
        reason: 'YouTube refused this computer.',
      })),
    );
    expect(outcome.deep[0]).toMatchObject({
      file: { used: 'none', reason: 'YouTube refused this computer.' },
      frames: { done: true, source: 'preview', available: 120 },
    });
    expect(log).toContain(`watch ${vid(1)} no file: YouTube refused this computer`);
    // The list grows as the job goes, so the page can show it while it runs.
    expect(steps.at(-1)?.supply).toHaveLength(3);
  });

  test('does not download a video too long to fit a file, and says why', async () => {
    const long = [video(1, 90_000, 1554), ...VIDEOS.slice(1)];

    const outcome = await run(world({ ...able, videos: long }));

    expect(log).not.toContain(`fetch ${vid(1)}`);
    expect(outcome.deep[0]?.file).toEqual({
      used: 'none',
      reason:
        'It is 25:54 long, and a copy small enough for Jgtube to download holds about 19:47 at most.',
    });
    expect(outcome.supply[0]?.videoId).toBe(vid(1));
    expect(log).toContain(`fetch ${vid(2)}`);
  });

  test('falls back to preview frames when ffmpeg fails on the file', async () => {
    const outcome = await run(
      world({ ...able, cut: () => ({ ok: false, reason: 'ffmpeg ended with an error' }) }),
    );

    expect(outcome.deep[0]?.frames).toMatchObject({ done: true, source: 'preview' });
  });

  test('passes the watching engine a smaller copy when the file is too large for it', async () => {
    const outcome = await run(
      world({
        ...able,
        own: { [vid(1)]: '/mine/big.mp4' },
        forWatching: () => ({ ok: true, path: '/temp/small.mp4' }),
      }),
    );

    expect(log).toContain(`watch ${vid(1)} file /temp/small.mp4`);
    expect(log).toContain(`cut ${vid(1)} from /mine/big.mp4`);
    expect(outcome.deep[0]?.watch).toMatchObject({ done: true });
  });

  test('keeps the engine choice for the frame studies and the writing', async () => {
    const outcome = await run(world(able), { only: 'codex' });

    expect(log).toContain(`study frames ${vid(1)} only codex`);
    expect(outcome.engine).toBe('codex');
  });
});

describe('a second breakdown of the same channel', () => {
  const able: World = {
    ffmpeg: true,
    watchesFiles: true,
    fetch: (videoId) => ({ ok: true, path: `/temp/${videoId}.mp4` }),
    watch: (videoId) => `Sound of ${videoId}.`,
  };

  test('reuses the stored watch notes and frame studies and only writes again', async () => {
    await run(world(able));
    log = [];

    const outcome = await run(world(able));

    expect(log.filter((line) => line.includes(vid(1)) || line.includes(vid(2)))).toEqual([
      `remove frames ${vid(1)}`,
      `remove frames ${vid(2)}`,
    ]);
    expect(outcome.deep[0]).toEqual({
      videoId: vid(1),
      title: 'Video 1',
      file: {
        used: 'none',
        reason: 'No file was needed: what a file is used for was kept from an earlier breakdown.',
      },
      watch: { done: true, by: 'agy', kept: true },
      frames: { done: true, by: 'claude', kept: true, source: 'file', available: 600 },
    });
    expect(log.at(-1)).toBe(`write ${CHANNEL} top 5 deep 3`);
  });

  test('makes everything again when the owner asks to start from nothing', async () => {
    await run(world(able));
    log = [];

    const outcome = await run(world(able), { fresh: true });

    expect(log).toContain(`fetch ${vid(1)}`);
    expect(log).toContain(`study frames ${vid(1)}`);
    expect(outcome.deep[0]?.watch).toEqual({ done: true, by: 'agy', kept: false });
  });

  test('replaces a study made from preview frames once a file can be had', async () => {
    await run(world());
    expect(studies.find(vid(1), 'frames')?.frames?.source).toBe('preview');
    log = [];

    const outcome = await run(world({ ffmpeg: true, own: { [vid(1)]: '/mine/1.mp4' } }));

    expect(log).toContain(`cut ${vid(1)} from /mine/1.mp4`);
    expect(outcome.deep[0]?.frames).toMatchObject({ kept: false, source: 'file', available: 600 });
    expect(studies.find(vid(1), 'frames')?.frames).toEqual({ source: 'file', available: 600 });
  });

  test('keeps the preview study when the file still cannot be had', async () => {
    await run(world());
    log = [];

    const outcome = await run(world({ ffmpeg: true }));

    expect(log).toContain(`fetch ${vid(1)}`);
    expect(log).not.toContain(`study frames ${vid(1)}`);
    expect(outcome.deep[0]?.frames).toMatchObject({ kept: true, source: 'preview' });
  });
});

describe('a breakdown that cannot go on', () => {
  test('has nothing to study in depth for a channel with no videos, and still writes', async () => {
    const outcome = await run(world({ videos: [] }));

    expect(outcome).toMatchObject({ storedVideos: 0, top: [], deep: [], text: 'THE BREAKDOWN' });
    expect(log).toEqual([`write ${CHANNEL} top 0 deep 0`]);
  });

  test('fails when the channel cannot be read', async () => {
    const deps = {
      ...world(),
      readChannel: async () => {
        throw new Error('YouTube could not be reached');
      },
    };

    await expect(run(deps)).rejects.toThrow('YouTube could not be reached');
  });

  test('fails with the engines’ reason when nobody could write', async () => {
    const deps = {
      ...world(),
      write: async () => {
        throw new EngineRunError('limit', 'Claude has hit its limit.');
      },
    };

    await expect(run(deps)).rejects.toMatchObject({ reason: 'limit' });
  });

  test('stops between steps when Jgtube is closing, and removes what it made', async () => {
    const stop = new AbortController();
    const deps = world({
      ffmpeg: true,
      stop,
      fetch: (videoId) => {
        stop.abort();
        return { ok: true, path: `/temp/${videoId}.mp4` };
      },
    });

    await expect(run(deps)).rejects.toThrow(/closing/);
    expect(log).not.toContain(`write ${CHANNEL} top 5 deep 3`);
    expect(log.filter((line) => line.startsWith('study'))).toEqual([]);
  });
});
